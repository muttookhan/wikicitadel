#!/usr/bin/env python3
"""Register lookup for Ask evidence — retrieval severance at the
packing seam (the build programme, 2026-10-20).

The wave-10 rule for the Ask door: superseded claims are
excluded from an answer's evidence by REGISTER LOOKUP, never
merely out-ranked (wave10-frontier-research.md find 8 — a
conflict-blind top-k retriever cannot be patched into
consistency). The registers' verdicts are compiled into the
severance list (``evaluation/retrieval-severance.json``,
generated by ``scripts/wiki_severance.py``); this module is the
Ask-side reader of that list.

:func:`filter_passages` checks candidate evidence passages
BEFORE packing (it is wired into
``evidence_packing.pack_evidence`` via its ``severance``
argument):

- a passage from a page-level severed page is dropped;
- a passage whose text CARRIES a severed claim (the severance
  TEXT match: any cue phrase as a contiguous token subsequence,
  or >= 4/5 of the claim's distinctive terms present) is dropped
  — from whatever page it was lifted, because a passage quoting
  the dead claim verbatim is the dead claim resurfacing as
  evidence.

Every drop is RECORDED, never silent: the returned ``severed``
list names the passage, the severance entry that cut it, and the
register line that entry derives from. When every candidate is
severed, ``all_evidence_severed`` is true and the honest outcome
is the abstention contract's path — an explicit abstention whose
reason names the severance (see ``tools/ask/pickup.md``).

An absent list changes nothing: severance is off and every
passage passes through.

Pure stdlib; importable without network access.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

TOKEN_RE = re.compile(r"[a-z0-9]+")

SEVERANCE_RELATIVE_PATH = "evaluation/retrieval-severance.json"


def repo_root() -> Path:
    """Repository root, derived from this file's location
    (tools/ask/severance.py -> parents[2])."""
    return Path(__file__).resolve().parents[2]


def default_severance_path() -> Path:
    return repo_root() / SEVERANCE_RELATIVE_PATH


def load_severance(path=None):
    """The parsed severance list, or None when absent/unreadable
    (severance off, behaviour unchanged)."""
    p = Path(path) if path is not None else default_severance_path()
    if not p.is_file():
        return None
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        return None
    if not isinstance(data, dict) \
            or data.get("kind") != "retrieval-severance":
        return None
    return data


def tokenize(text: str):
    """The wiki tokenizer (identical rule to
    scripts/wiki_search.py): lowercase [a-z0-9]+ runs, len >= 2."""
    return [t for t in TOKEN_RE.findall(str(text).lower())
            if len(t) >= 2]


# -- Matching (mirrors scripts/wiki_severance.py's TEXT rule) ------------------

def _phrase_hit(tokens, phrase):
    n = len(phrase)
    if n == 0 or n > len(tokens):
        return False
    phrase = list(phrase)
    return any(tokens[i:i + n] == phrase
               for i in range(len(tokens) - n + 1))


def _text_matches(tokens, entry):
    """TEXT match: the text carries the entry's severed claim —
    any cue phrase, or >= 4/5 of the distinctive terms."""
    cues = entry.get("cues") or {}
    for phrase in cues.get("phrases") or []:
        if _phrase_hit(tokens, phrase):
            return True
    terms = cues.get("terms") or []
    if terms:
        have = set(tokens)
        present = sum(1 for t in terms if t in have)
        if present * 5 >= len(terms) * 4:
            return True
    return False


def _page_key(page) -> str:
    """Normalise a page reference for comparison: page ids
    (``sources/hindsight``), repo paths (``wiki/sources/
    hindsight.md``) and bare stems all reduce to the path under
    ``wiki/`` without the suffix."""
    p = str(page or "").strip().replace("\\", "/")
    if p.endswith(".md"):
        p = p[:-3]
    if p.startswith("wiki/"):
        p = p[len("wiki/"):]
    return p


def passage_severed_by(passage: dict, severance):
    """The severance entry that cuts *passage*, or None.

    Page-level entries cut every passage from their page;
    claim entries cut any passage whose text carries the claim.
    Entries are consulted in list order, so the returned entry
    is deterministic."""
    if not severance:
        return None
    entries = severance.get("entries") or []
    if not entries:
        return None
    page = _page_key(passage.get("page"))
    tokens = None
    for entry in entries:
        if entry.get("kind") == "page":
            if page and page == _page_key(entry.get("page")):
                return entry
            continue
        if tokens is None:
            tokens = tokenize(passage.get("passage", ""))
        if _text_matches(tokens, entry):
            return entry
    return None


def filter_passages(passages, severance):
    """Split candidate evidence passages by the severance list.

    Returns a dict:

    - ``kept``: the passages that survive, in the caller's order;
    - ``severed``: one record per dropped passage — the passage
      itself plus ``severed_by`` (the entry id), ``entry_kind``
      and ``source`` (the register + line the entry derives
      from), so the drop is on the record, never silent;
    - ``all_evidence_severed``: true when at least one passage
      was offered and every one was severed — the signal that the
      honest outcome is an abstention naming the severance.
    """
    kept = []
    severed = []
    for passage in passages or []:
        entry = passage_severed_by(passage, severance)
        if entry is None:
            kept.append(passage)
        else:
            record = dict(passage)
            record["severed_by"] = entry.get("id")
            record["entry_kind"] = entry.get("kind")
            record["source"] = entry.get("source")
            severed.append(record)
    return {
        "kept": kept,
        "severed": severed,
        "all_evidence_severed": bool(severed) and not kept,
    }
