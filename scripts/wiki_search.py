def _successor_map(governance):
    """{severance entry id: {successor page paths}} from the
    artefact's chains — the exemption table for stage 5."""
    out = {}
    for eid, chain in (governance.get("chains") or {}).items():
        pages = chain.get("successors") or []
        if pages:
            out[eid] = set(pages)
    return out


def apply_governance(ranked, governance):
    """Stage 6: withhold pages in a withheld governance state;
    annotate kept governed pages in their detail. Returns
    (kept, withheld) — withheld is [{"path", "reasons"}] in
    ranked order, so every withholding carries its named
    reason. Scores and the order of kept results are untouched.

    A page with NO record in the artefact is UNGOVERNED: it is
    kept, unannotated, and never treated as superseded — the
    absence of lifecycle state is a state of its own, not an
    adverse signal."""
    pages = governance.get("pages") or {}
    kept, withheld = [], []
    for item in ranked:
        score, p, text, detail = item
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) \
            else str(p)
        record = pages.get(rel)
        if record is None:
            kept.append(item)
            continue
        if record.get("state") == "withheld":
            withheld.append({"path": rel,
                             "reasons": record.get("reasons") or []})
            continue
        note = {"state": record.get("state"),
                "reasons": record.get("reasons") or []}
        for key in ("proposition", "successor", "lifecycle"):
            if record.get(key) is not None:
                note[key] = record[key]
        kept.append((score, p, text,
                     dict(detail, governance=note)))
    return kept, withheld

