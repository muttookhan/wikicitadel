LAST_SEVERANCE = {"applied": False, "excluded": []}


def load_severance(path=None):
    """The parsed severance list, or None when absent/unreadable
    (severance off, behaviour unchanged). Cached by file stamp."""
    p = Path(path) if path is not None else SEVERANCE_PATH
    try:
        st = p.stat()
    except OSError:
        return None
    key = (str(p), st.st_mtime_ns, st.st_size)
    if key not in _SEVERANCE_CACHE:
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except (ValueError, OSError):
            data = None
        if not isinstance(data, dict) \
                or data.get("kind") != "retrieval-severance":
            data = None
        _SEVERANCE_CACHE.clear()
        _SEVERANCE_CACHE[key] = data
    return _SEVERANCE_CACHE[key]


def _resolve_severance(severance):
    """None -> load the default list; False -> severance off;
    a dict -> use it as the list."""
    if severance is None:
        return load_severance()
    if severance is False:
        return None
    return severance


def _sev_phrase_hit(tokens, phrase):
    n = len(phrase)
    if n == 0 or n > len(tokens):
        return False
    phrase = list(phrase)
    return any(tokens[i:i + n] == phrase
               for i in range(len(tokens) - n + 1))


def _sev_terms_present(tokens, terms):
    have = set(tokens)
    return sum(1 for t in terms if t in have)


def _sev_text_matches(tokens, entry):
    cues = entry.get("cues") or {}
    for phrase in cues.get("phrases") or []:
        if _sev_phrase_hit(tokens, phrase):
            return True
    terms = cues.get("terms") or []
    if terms and _sev_terms_present(tokens, terms) * 5 \
            >= len(terms) * 4:
        return True
    return False


def _sev_query_matches(query_terms, entry):
    cues = entry.get("cues") or {}
    for phrase in cues.get("phrases") or []:
        if _sev_phrase_hit(query_terms, phrase):
            return True
    terms = cues.get("terms") or []
    if terms:
        need = max(3, (len(terms) + 1) // 2)
        if _sev_terms_present(query_terms, terms) >= need:
            return True
    return False


def apply_severance(ranked, query_terms, severance, successors=None,
                    exempted_out=None):
    """Exclude severed results from a ranked list of
    (score, path, text, detail). A result is excluded when its
    page carries a page-level entry, or when the query matches a
    claim entry's cues AND the result's text carries the claim
    (TEXT match). Returns (kept, excluded) — excluded is
    [{"path", "entries": [severance ids]}] in ranked order, so
    the exclusion is reported, never silent.

    `successors` (W1.5): {entry id: {page paths}} — a page
    named as an entry's successor (it carries the claim's
    current form; see scripts/wiki_governance.py) is exempt
    from THAT entry's text-match exclusion: its dead-form text
    is recounted as history, and cutting it would cut the audit
    chain the supersession exists to keep. Page-level entries
    are never exempted. Suppressed hits are appended to
    `exempted_out` (when given) as {"path", "entries"} — the
    exemption is recorded, never silent. With successors=None
    (the default) the behaviour is exactly the pre-W1.5 rule."""
    if not severance:
        return ranked, []
    entries = severance.get("entries") or []
    page_entries = [e for e in entries if e.get("kind") == "page"]
    claim_entries = [e for e in entries if e.get("kind") != "page"]
    q_matched = [e for e in claim_entries
                 if _sev_query_matches(query_terms, e)]
    kept, excluded = [], []
    for item in ranked:
        _score, p, text, _detail = item
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) \
            else str(p)
        hit_ids = [e["id"] for e in page_entries
                   if e.get("page") == rel]
        exempted_ids = []
        if not hit_ids and q_matched:
            tokens = tokenize(text)
            for e in q_matched:
                if not _sev_text_matches(tokens, e):
                    continue
                if successors and rel in successors.get(
                        e["id"], ()):
                    exempted_ids.append(e["id"])
                else:
                    hit_ids.append(e["id"])
        if hit_ids:
            excluded.append({"path": rel, "entries": hit_ids})
        else:
            kept.append(item)
            if exempted_ids and exempted_out is not None:
                exempted_out.append({"path": rel,
                                     "entries": exempted_ids})
    return kept, excluded

