def build_link_graph(docs):
    """Undirected adjacency over the doc list: {idx: sorted [idx]}.

    Wikilinks are read from each doc's text with code spans/fences
    stripped (a `[[wikilink]]` quoted in backticks is syntax, not a
    link — the wiki_validate.py convention). Targets resolve by
    repo-relative path without suffix, then by file stem, then by
    basename stem — the same precedence the validator and the Lens
    use, so all three rankers walk the same graph.
    """
    by_key = {}
    for i, (p, _t) in enumerate(docs):
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)
        by_key.setdefault(Path(rel).stem, i)
        by_key.setdefault(str(Path(rel).with_suffix("")), i)
    adj = {i: set() for i in range(len(docs))}
    for i, (_p, text) in enumerate(docs):
        body = CODESPAN_RE.sub("", FENCE_RE.sub("", text))
        for target in LINK_RE.findall(body):
            t = target.strip()
            if not t:
                continue
            j = by_key.get(t) or by_key.get(Path(t).name)
            if j is None or j == i:
                continue
            adj[i].add(j)
            adj[j].add(i)
    return {i: sorted(js) for i, js in adj.items()}


def personalized_pagerank(adj, seeds, damping=PPR_DAMPING,
                          tol=1e-7, max_iter=200):
    """Power-iteration PPR. `seeds`: {idx: weight} (need not be
    normalised). Dangling nodes redistribute over the seed
    distribution, keeping the walk a proper PPR. Returns
    {idx: probability} over all nodes in adj."""
    n = len(adj)
    if n == 0 or not seeds:
        return {}
    total = float(sum(seeds.values())) or 1.0
    teleport = {i: seeds.get(i, 0.0) / total for i in adj}
    rank = dict(teleport)
    for _ in range(max_iter):
        dangling = sum(rank[i] for i in adj if not adj[i])
        new = {}
        for i in adj:
            incoming = 0.0
            for j in adj[i]:
                if adj[j]:
                    incoming += rank[j] / len(adj[j])
            new[i] = (1.0 - damping) * teleport[i] \
                + damping * (incoming + dangling * teleport[i])
        delta = sum(abs(new[i] - rank[i]) for i in adj)
        rank = new
        if delta < tol:
            break
    return rank


_RERANK_MODULE = None


# -- Standalone fallback for the reranker seam (coordinator glue,
# 2026-10-22, on the W1.8 lane's cross-lane report) ----------------
# This module is copied ALONE into fixture trees by established
# harness patterns in this repo (the traverse and MCP-read
# fixtures), where the seam's sibling file is absent. The seam
# therefore degrades to the legacy ranking path instead of
# failing: the fallback below reproduces wiki_rerank.py's
# DEFAULT coverage reranker arithmetic exactly (same float
# operations, same operands), so scores, relevances and
# below-cutoff flags are identical; the degradation is visible,
# never silent — hybrid_rank stamps rerank_seam on every result
# detail while the fallback is in force. Any other reranker kind
# raises, naming the absent sibling: a swapped reranker is never
# silently substituted (the seam's own rule).

class _FallbackRerankSignal:
    __slots__ = ("multiplier", "relevance", "signals")

    def __init__(self, multiplier, relevance, signals=None):
        self.multiplier = multiplier
        self.relevance = relevance
        self.signals = signals or {}


class _FallbackCoverageReranker:
    """wiki_rerank.CoverageReranker, replicated exactly."""
    name = "coverage"
    kind = "coverage"

    def __init__(self, coverage_w=0.25, title_w=0.15, max_lift=None):
        self.coverage_w = coverage_w
        self.title_w = title_w
        self.max_lift = (coverage_w + title_w) if max_lift is None \
            else max_lift

    def rerank(self, query_terms, candidates):
        out = {}
        for cand in candidates:
            cov = cand.get("coverage", 0.0)
            t_frac = cand.get("title_frac", 0.0)
            mult = 1.0 + self.coverage_w * cov \
                + self.title_w * t_frac
            rel = (mult - 1.0) / self.max_lift \
                if self.max_lift > 0 else 0.0
            rel = 0.0 if rel < 0.0 else (1.0 if rel > 1.0 else rel)
            out[cand["key"]] = _FallbackRerankSignal(
                multiplier=mult, relevance=rel,
                signals={"coverage": cov, "title_frac": t_frac})
        return out


class _FallbackRelevanceCutoff:
    """wiki_rerank.RelevanceCutoff, replicated exactly."""

    def __init__(self, threshold=0.575):
        self.threshold = threshold

    def below(self, relevance: float) -> bool:
        return relevance < self.threshold


class _FallbackRerankModule:
    """Stand-in for scripts/wiki_rerank.py when this file is
    used standalone. IS_FALLBACK is the marker hybrid_rank
    reads to stamp the degradation on result details."""
    IS_FALLBACK = True
    DEFAULT_RELEVANCE_CUTOFF = 0.575
    RelevanceCutoff = _FallbackRelevanceCutoff

    @staticmethod
    def get_reranker(name, **kwargs):
        if name == "coverage":
            return _FallbackCoverageReranker(
                coverage_w=kwargs.get("coverage_w", 0.25),
                title_w=kwargs.get("title_w", 0.15),
                max_lift=kwargs.get("max_lift"))
        raise ValueError(
            f"reranker {name!r} needs scripts/wiki_rerank.py, "
            "which is absent beside this standalone copy of "
            "wiki_search.py; only the default coverage path is "
            "available in fallback mode")

    @staticmethod
    def listwise_enabled(explicit=False, env=None):
        if explicit:
            return True
        import os
        env = os.environ if env is None else env
        return str(env.get("WIKI_RERANK_LISTWISE", "")).lower() \
            in ("1", "true", "yes", "on")


