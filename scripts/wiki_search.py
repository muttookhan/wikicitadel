def hybrid_rank(query_terms, docs, adj=None, severance=None,
                reranker=None, relevance_cutoff=None, listwise=None,
                enable_listwise=False, governance=None,
                expansion=None, onehop=None, iterate=None):
    """Hybrid recall: BM25 + PPR graph, then the two Hindsight
    stages (2026-10-19). Returns [(score, path, text, detail)]
    sorted by (-score, path); detail = {"bm25": float, "ppr":
    float, "via": "bm25" | "graph" | "both", "temporal": float,
    "rerank": float}. Docs found only by the walk (bm25 == 0) are
    included when their PPR clears PPR_GRAPH_FLOOR of the maximum
    PPR — the walk must surface neighbours, not the whole
    connected component.

    Stage 3 (temporal): when the query carries temporal intent,
    each candidate gains TEMPORAL_W * (1 - date-rank share) over
    the candidate set, newest page first (ties: higher BM25, then
    path). Stage 4 (rerank): results in the top RERANK_POOL of
    the stage-2 order are scaled by 1 + RERANK_COVERAGE_W * (share
    of distinct query terms in the first RERANK_LEAD_TOKENS
    tokens) + RERANK_TITLE_W * (share in the title). Both stages
    were tuned on the golden set; see the module docstring for
    the measured before/after.

    Stage 5 (severance): the ranked list is filtered
    against the severance list (see apply_severance). The
    `severance` argument: None loads the default list from
    evaluation/retrieval-severance.json, False disables the
    stage, a dict is used as the list.

    Stage 6 (governance, W1.5): the ranked list is filtered
    against the governance artefact (see apply_governance) and
    stage 5 consults its supersession chains (the successor
    exemption). The `governance` argument mirrors severance's:
    None loads the default artefact from
    evaluation/retrieval-governance.json, False disables BOTH
    governance effects (restoring the pre-governance pipeline
    exactly), a dict is used as the artefact. An absent
    artefact disables the stage the same way.

    Reranker seam (W1.1): stage 4's multiplier comes from the
    `reranker` argument (a scripts/wiki_rerank.py Reranker);
    None builds the default coverage reranker, which reproduces
    the pre-seam arithmetic exactly. A swapped reranker may only
    scale pool candidates, through the same bounded lift. Every
    detail gains "reranker", "rerank_relevance" and
    "below_cutoff" (against `relevance_cutoff`, default
    wiki_rerank.DEFAULT_RELEVANCE_CUTOFF). `listwise` (a
    ListwiseReranker) reorders the finished ranking ONLY when
    the gate is open — `enable_listwise` or the
    WIKI_RERANK_LISTWISE env var; off by default.

    Expansion (W3): `expansion` is an expansion record built
    by scripts/wiki_hyde_expand.py, or None (the default — the
    stage does not exist and the pipeline is the pre-W3 one
    exactly). Stage 0 below merges the record's terms into
    BM25 recall at their recorded weights; every later stage
    reads the original `query_terms` unchanged, and stages
    5–6 filter the expanded list unchanged. Each candidate's
    detail gains "expansion_bm25" (its weighted expansion
    contribution to the recall score) while the stage is on,
    and the record is kept in LAST_EXPANSION.

    One-hop vote (W3): `onehop` is None (the default — the
    stage does not exist and the pipeline is the pre-item one
    exactly), True for the stage at its stated constants, or
    a {"k":..., "weight":...} dict overriding them. Stage 4c
    below (scripts/wiki_onehop_vote.py) adds each page's
    single bounded gain — weight / (k + best seed rank) —
    to its FINAL score after the rerank stages, and admits
    neighbours no stage recalled; stages 5–6 then filter the
    voted list unchanged. Each voted candidate's detail
    gains "onehop_vote" (gain, seed, seed rank, the edge's
    W1.8 label, admission flag), and the full record is kept
    in LAST_ONEHOP.

    Iteration (W3): `iterate` is None (the default — the
    stage does not exist and the pipeline is the pre-item
    one exactly), True for the loop at its stated constants,
    or a {"max_passes":..., "weight":...} dict overriding
    them. After stage 6, scripts/wiki_iterate.py runs the
    bounded loop: each later pass re-runs THIS pipeline with
    refinement terms drawn from the previous pass's governed
    output, and the passes are fused by reciprocal rank.
    A loop that stops after one pass returns pass 1's list
    unchanged. The full record is kept in LAST_ITERATION."""
    # --- Stage 0: HyDE lexical expansion (W3, OPT-IN) ---
    # BM25 in bm25_rank is a plain sum over term contributions
    # (one idf-weighted term score per query-term occurrence),
    # so the merged recall score of a document is its original
    # score plus, per expansion term, weight x its score for
    # that term. Terms are grouped by weight so each distinct
    # weight costs one extra bm25_rank pass. Nothing else in
    # the pipeline sees the expansion terms: qset, title match,
    # temporal intent and the severance query-match all keep
    # reading `query_terms` itself.
    exp_terms = []
    if expansion:
        exp_terms = [(e["term"], float(e["weight"]))
                     for e in expansion.get("expansion_terms") or []]
    LAST_EXPANSION["applied"] = bool(exp_terms)
    LAST_EXPANSION["record"] = expansion if exp_terms else None
    LAST_ONEHOP["applied"] = bool(onehop)
    LAST_ONEHOP["record"] = None
    LAST_ITERATION["applied"] = bool(iterate)
    LAST_ITERATION["record"] = None
    base = bm25_rank(query_terms, docs)
    exp_by_path = {}
    if exp_terms:
        merged = {p: [s, t] for s, p, t in base}
        by_weight = {}
        for term, w in exp_terms:
            by_weight.setdefault(w, []).append(term)
        for w in sorted(by_weight):
            for s, p, t in bm25_rank(by_weight[w], docs):
                contrib = w * s
                if p in merged:
                    merged[p][0] += contrib
                else:
                    merged[p] = [contrib, t]
                exp_by_path[p] = exp_by_path.get(p, 0.0) + contrib
        base = sorted(((s, p, t) for p, (s, t) in merged.items()),
                      key=lambda r: (-r[0], str(r[1])))
    if not base:
        if iterate:
            _record_empty_iteration(iterate, query_terms, docs,
                                    expansion)
        return []
    if adj is None:
        adj = build_link_graph(docs)
    index_of = {p: i for i, (p, _t) in enumerate(docs)}
    bm25_by_idx = {}
    for score, p, _t in base:
        bm25_by_idx[index_of[p]] = score
    exp_by_idx = {index_of[p]: c for p, c in exp_by_path.items()}
    seeds = {}
    for score, p, _t in base[:PPR_SEEDS]:
        seeds[index_of[p]] = score
    ppr = personalized_pagerank(adj, seeds)
    max_b = max(bm25_by_idx.values())
    max_p = max(ppr.values()) if ppr else 0.0
    out = []
    for i, (p, text) in enumerate(docs):
        b = bm25_by_idx.get(i, 0.0)
        pr = ppr.get(i, 0.0)
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)
        if rel in STRUCTURAL_PATHS:
            pr = 0.0
        if b <= 0 and not (max_p > 0 and pr >= PPR_GRAPH_FLOOR * max_p):
            continue
        score = (b / max_b if max_b else 0.0) \
            + HYBRID_ALPHA * (pr / max_p if max_p else 0.0)
        via = "both" if b > 0 and pr > 0 else ("bm25" if b > 0 else "graph")
        detail = {"bm25": round(b, 4), "ppr": round(pr, 6), "via": via}
        if exp_terms:
            detail["expansion_bm25"] = round(exp_by_idx.get(i, 0.0), 4)
        out.append((score, p, text, detail))
    out.sort(key=lambda r: (-r[0], str(r[1])))
    if not out:
        if iterate:
            _record_empty_iteration(iterate, query_terms, docs,
                                    expansion)
        return out

    # --- Stage 3: temporal component (intent-gated) ---
    # The date-rank share itself is computed unconditionally as
    # the `recency` feature (other rank expressions use it); it
    # only ENTERS the score, as `temporal`, under temporal intent.
    temp_by_idx = {}
    cand = [index_of[p] for _s, p, _t, _d in out]

    def _date_key(i):
        d = doc_date(docs[i][1])
        return (d is not None, d or "", bm25_by_idx.get(i, 0.0))

    t_order = sorted(sorted(cand, key=lambda i: str(docs[i][0])),
                     key=_date_key, reverse=True)
    n_cand = len(cand) or 1
    recency_by_idx = {}
    for r, i in enumerate(t_order):
        recency_by_idx[i] = 1.0 - r / n_cand
    if temporal_intent(query_terms):
        temp_by_idx = dict(recency_by_idx)

    # --- Stage 4: coverage rerank + the rank expression ---
    # Features are computed per candidate, then the final score
    # is ONE evaluation of the named expression
    # RANK_EXPRESSIONS["hybrid-current"] per candidate (the
    # Vespa-style single pass): (blend_norm + 0.3*temporal) *
    # rerank + title_boost, where blend_norm is the stage-2
    # blend (bm25_norm + 0.6*ppr_norm) divided by the candidate
    # set's maximum blend (max_s). That renormalisation is the
    # pre-TB7 arithmetic exactly — one division of the blend
    # itself — and it is load-bearing, not cosmetic: the
    # abstention gate's tau is calibrated to that ABSOLUTE
    # scale. Dropping it (as first shipped) left ordering
    # unchanged but inflated weak-match top scores past tau and
    # the abstention battery fell to 9/12; a per-term rescale
    # still flipped the knife-edge case AB-008 (calibrated to
    # sit exactly at tau), so the division is applied to the
    # blend as a whole. The title boost (row 1) is the intended
    # behaviour change and enters unscaled.
    qset = set(query_terms)
    max_deg = max((len(adj.get(i, ())) for i in cand), default=0) or 1
    ast = rank_expression_ast("hybrid-current")
    max_s = max((s for s, _p, _t, _d in out), default=0.0)
    # The rerank multiplier is produced through the wiki_rerank
    # seam (W1.1). The default reranker is the legacy coverage
    # reranker and reproduces the pre-seam arithmetic exactly
    # (1 + RERANK_COVERAGE_W * cov + RERANK_TITLE_W * t_frac,
    # same operands, same order); a swapped reranker sees the
    # same pool and the same bounded lift.
    rr = _load_rerank_module()
    seam = reranker if reranker is not None else rr.get_reranker(
        "coverage", coverage_w=RERANK_COVERAGE_W,
        title_w=RERANK_TITLE_W,
        max_lift=RERANK_COVERAGE_W + RERANK_TITLE_W,
        tokenize=tokenize)
    cutoff = rr.RelevanceCutoff(
        rr.DEFAULT_RELEVANCE_CUTOFF if relevance_cutoff is None
        else relevance_cutoff)
    # Pass 1: per-candidate features (unchanged) + the seam's
    # candidate views for the rerank pool — the only candidates
    # any reranker may scale, as before the seam.
    rows = []
    views = []
    for pos, (score, p, text, detail) in enumerate(out):
        i = index_of[p]
        t = temp_by_idx.get(i, 0.0)
        cov = t_frac = 0.0
        if pos < RERANK_POOL and qset:
            lead = set(tokenize(text)[:RERANK_LEAD_TOKENS])
            cov = len(qset & lead) / len(qset)
            title_toks = set(tokenize(doc_title(text)))
            t_frac = len(qset & title_toks) / len(qset)
            views.append({"key": i, "title": doc_title(text),
                          "text": text, "coverage": cov,
                          "title_frac": t_frac})
        boost, match_kind = title_boost_value(
            query_terms, doc_title(text), p.stem)
        rel_i = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)
        pr_i = 0.0 if rel_i in STRUCTURAL_PATHS else ppr.get(i, 0.0)
        features = {
            "bm25": bm25_by_idx.get(i, 0.0),
            "bm25_norm": (bm25_by_idx.get(i, 0.0) / max_b) if max_b else 0.0,
            "ppr": pr_i,
            "ppr_norm": (pr_i / max_p) if max_p else 0.0,
            "blend_norm": (score / max_s) if max_s else 0.0,
            "temporal": t, "recency": recency_by_idx.get(i, 0.0),
            "coverage": cov, "title_frac": t_frac,
            "title_boost": boost,
            "exact_title": 1.0 if match_kind == "exact" else 0.0,
            "stem_title": 1.0 if match_kind == "stem" else 0.0,
            "importance": len(adj.get(i, ())) / max_deg,
        }
        rows.append((score, p, text, detail, features, t, boost,
                     match_kind))
    signals = seam.rerank(query_terms, views) if views else {}
    final = []
    for score, p, text, detail, features, t, boost, match_kind in rows:
        sig = signals.get(index_of[p])
        mult = sig.multiplier if sig is not None else 1.0
        relevance = sig.relevance if sig is not None else 0.0
        features["rerank"] = mult
        ns = eval_rank_expression(ast, features)
        detail = dict(detail, temporal=round(t, 4), rerank=round(mult, 4),
                      title_boost=boost, title_match=match_kind,
                      rank_expression="hybrid-current",
                      reranker=seam.name,
                      rerank_relevance=round(relevance, 4),
                      below_cutoff=cutoff.below(relevance))
        if getattr(rr, "IS_FALLBACK", False):
            detail["rerank_seam"] = (
                "legacy-fallback (wiki_rerank.py absent)")
        final.append((ns, p, text, detail))
    final.sort(key=lambda r: (-r[0], str(r[1])))

    # --- Stage 4b: listwise reordering (W1.1, GATED) ---
    # Off unless a ListwiseReranker was supplied AND the gate is
    # open (enable_listwise or WIKI_RERANK_LISTWISE). Permutes
    # the finished ranking; scores travel with their documents,
    # so the tau gate's per-document semantics are unchanged.
    # Moved entries are stamped "listwise_from" (their pre-stage
    # position) so the permutation is never silent.
    if listwise is not None and rr.listwise_enabled(enable_listwise):
        by_key = {}
        lviews = []
        for pos, (ns, p, text, detail) in enumerate(final):
            key = str(p)
            by_key[key] = (ns, p, text, detail, pos)
            lviews.append({"key": key, "title": doc_title(text),
                           "text": text, "coverage": 0.0,
                           "title_frac": 0.0})
        reordered = listwise.rerank_order(query_terms, lviews)
        new_final = []
        for new_pos, view in enumerate(reordered):
            ns, p, text, detail, old_pos = by_key[view["key"]]
            if old_pos != new_pos:
                detail = dict(detail, listwise_from=old_pos)
            new_final.append((ns, p, text, detail))
        final = new_final

    # --- Stage 4c: one-hop wikilink vote (W3, OPT-IN) ---
    # A page one wikilink hop from a lexical hit gains the
    # crewhaus half-weight term 0.5 / (60 + best seed rank)
    # (scripts/wiki_onehop_vote.py) — a single bounded
    # corroboration, added to the FINAL score: no
    # renormalisation follows, so un-voted pages keep their
    # scores exactly and the abstention threshold's absolute
    # scale is perturbed only where a vote actually lands.
    # Neighbours no stage recalled are admitted on the vote
    # alone. Stages 5–6 below filter the voted list exactly
    # as they filter the un-voted one — a vote can never
    # resurrect a severed or withheld page.
    if onehop:
        cfg = onehop if isinstance(onehop, dict) else {}
        final, vote_record = _load_onehop_module().apply_vote_stage(
            final, docs, adj, index_of, ppr,
            k=cfg.get("k", 60), weight=cfg.get("weight", 0.5))
        LAST_ONEHOP["record"] = vote_record

    # --- Stage 5: retrieval severance  ---
    # Exclusion by register lookup, after every ranking stage:
    # severed pages, and carriers of a severed claim the query
    # itself hunts, are removed — never merely down-ranked. The
    # pass is recorded in LAST_SEVERANCE for the CLI / pack.
    # With governance active, its supersession chains exempt a
    # severed claim's named successor pages from that claim's
    # text-match exclusion (recorded in LAST_GOVERNANCE).
    sev = _resolve_severance(severance)
    gov = _resolve_governance(governance)
    LAST_SEVERANCE["applied"] = bool(sev)
    LAST_SEVERANCE["excluded"] = []
    LAST_GOVERNANCE["applied"] = bool(gov)
    LAST_GOVERNANCE["withheld"] = []
    LAST_GOVERNANCE["exempted"] = []
    if sev:
        final, excluded = apply_severance(
            final, query_terms, sev,
            successors=_successor_map(gov) if gov else None,
            exempted_out=LAST_GOVERNANCE["exempted"])
        LAST_SEVERANCE["excluded"] = excluded

    # --- Stage 6: truth-aware governance (W1.5) ---
    # Pages in a withheld governance state (superseded, retired
    # claim, closed validity window) leave the default ranking
    # WITH their named reasons; governed-but-live pages keep
    # their score and carry their state in the detail.
    # Ungoverned pages — no record in the artefact — pass
    # through untouched. No score or order changes among kept
    # results: the abstention threshold's calibration stands.
    if gov:
        final, withheld = apply_governance(final, gov)
        LAST_GOVERNANCE["withheld"] = withheld
        if LAST_GOVERNANCE["exempted"]:
            # A successor page with no artefact record of its
            # own still carries why it survived the severance
            # pass — the exemption is never silent.
            exempted = {e["path"]: e["entries"]
                        for e in LAST_GOVERNANCE["exempted"]}
            stamped = []
            for score, p, text, detail in final:
                rel = str(p.relative_to(ROOT)) \
                    if p.is_relative_to(ROOT) else str(p)
                if rel in exempted and "governance" not in detail:
                    detail = dict(detail, governance={
                        "state": "successor",
                        "reasons": [
                            "named successor for "
                            + ", ".join(exempted[rel])
                            + " — carries the current form; the "
                              "superseded form is recounted as "
                              "history"]})
                stamped.append((score, p, text, detail))
            final = stamped

    # --- Stage 7: iterative retrieval (W3, OPT-IN) ---
    # The finished, governed ranking seeds a bounded loop
    # (scripts/wiki_iterate.py): refinement terms are drawn
    # from THIS list — post-severance, post-governance — so
    # a withheld or severed page's text never enters the
    # draft vocabulary, and each later pass re-runs the
    # whole pipeline (stages 5–6 included) with those terms
    # merged at stage 0, so its output is filtered again.
    # The passes are fused by reciprocal rank (k = 60); a
    # loop that stops after one pass returns this list
    # unchanged, calibrated scale and all.
    if iterate:
        cfg = iterate if isinstance(iterate, dict) else {}
        mod = _load_iterate_module()

        def _pass_rank(exp_rec, _adj=adj):
            return hybrid_rank(
                query_terms, docs, adj=_adj, severance=severance,
                reranker=reranker,
                relevance_cutoff=relevance_cutoff,
                listwise=listwise, enable_listwise=enable_listwise,
                governance=governance, expansion=exp_rec,
                onehop=onehop)

        final, iteration_record = mod.run_iteration(
            _pass_rank, query_terms, docs, final,
            caller_expansion=expansion,
            max_passes=cfg.get("max_passes",
                               mod.DEFAULT_MAX_PASSES),
            weight=cfg.get("weight", mod.REFINE_WEIGHT))
        LAST_ITERATION["record"] = iteration_record
        # The inner pass calls reset the LAST_* globals for
        # their own (non-iterating) runs; the record above is
        # this call's, and the stage WAS applied here.
        LAST_ITERATION["applied"] = True
    return final


