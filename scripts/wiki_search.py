def bm25_rank(query_terms, docs):
    """Return [(score, path, text)] sorted by score desc, score > 0."""
    n = len(docs)
    if n == 0:
        return []
    doc_tokens = []
    doc_tf = []
    df = Counter()
    total_len = 0
    for _p, text in docs:
        toks = tokenize(text)
        doc_tokens.append(toks)
        total_len += len(toks)
        tf = Counter(toks)
        doc_tf.append(tf)
        for term in tf:
            df[term] += 1
    avgdl = total_len / n if n else 1.0

    idf = {}
    for term in set(query_terms):
        d = df.get(term, 0)
        idf[term] = math.log(1.0 + (n - d + 0.5) / (d + 0.5))

    scored = []
    for (p, text), toks, tf in zip(docs, doc_tokens, doc_tf):
        dl = len(toks)
        score = 0.0
        for term in query_terms:
            f = tf.get(term, 0)
            if not f:
                continue
            denom = f + K1 * (1.0 - B + B * dl / avgdl)
            score += idf[term] * (f * (K1 + 1.0)) / denom
        if score > 0:
            scored.append((score, p, text))
    scored.sort(key=lambda r: (-r[0], str(r[1])))
    return scored


