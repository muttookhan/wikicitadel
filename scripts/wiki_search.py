# Retrieval severance : exclusion by register lookup.
# The matching rules mirror scripts/wiki_severance.py exactly —
# cue phrases as contiguous token subsequences; distinctive terms
# at 4/5 presence for a TEXT match, at >= half (min 3) for a QUERY
