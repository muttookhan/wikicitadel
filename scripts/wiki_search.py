#!/usr/bin/env python3
"""Hybrid full-text + graph search over the LLM Wiki (wiki/ + raw/).

Why this exists: wiki/index.md is a lossy catalog — it cannot hold
every name, number and phrase a query might target. Per the measured
findings in the Karpathy gist comment thread, queries should UNION
index-selected pages with full-text results. This tool is the
full-text half of that union; --with-index adds the index half.

Ranking (WikiCitadel v1) is
HYBRID by default:

  1. Okapi BM25 (unchanged from the original tool: k1 = 1.5,
     b = 0.75, non-negative Robertson IDF) over the corpus;
  2. Personalized PageRank over the [[wikilink]] graph, seeded by
     the top BM25 hits — pages the best textual hits point to (and
     that point back) gain score even when their own text barely
     matches the query;
  3. base = bm25/max_bm25 + HYBRID_ALPHA * ppr/max_ppr;
  4. TEMPORAL (adapted from Hindsight's recall — see
     wiki/sources/hindsight.md): only when the query carries
     temporal intent, candidates gain TEMPORAL_W * (1 - their
     date-rank share), newest first;
  5. RERANK (same adaptation): the top RERANK_POOL
     results are scaled by their query-term coverage of the title
     and of the document's first RERANK_LEAD_TOKENS tokens — the
     lead window is what keeps long pages from winning on coverage
     saturation alone.

Golden-set measurement for stages 4–5 (corpus of the
day): MRR 0.432 -> 0.483, coverage @1 0.13 -> 0.20, @5 0.80 ->
0.87, @10 0.93 -> 1.00 (evaluation/results/). The pure-RRF
fusion in --engine hindsight measured WORSE on MRR (0.34–0.38
across the day's runs, vs 0.432 hybrid of the same corpus) and
stays experimental; stages 4–5 are the part of the recipe that
earned its place.

--engine bm25 reproduces the original ranking exactly (bm25_rank is
byte-for-byte the original algorithm; the Lens build parity-checks
it, and now the hybrid ranking too, at build time).

--pack emits an EVIDENCE PACK (JSON): the included hits with their
score components and snippets, plus an explicit OMISSIONS list —
the highest-ranked results left out by the --top cut, with the
reason. Nothing is silently dropped.

Retrieval severance (WikiCitadel v1):
the hybrid engine consults the severance list
(evaluation/retrieval-severance.json, generated by
scripts/wiki_severance.py from the decisions + treatment
registers) and EXCLUDES results whose page is severed, or whose
text carries a severed claim the query itself goes looking for
(the cue path from query to dead claim is cut; the record stays
findable by other queries — supersede-don't-delete). Exclusions
are counted in LAST_SEVERANCE, printed by the CLI, and carried in
the evidence pack's "severance" block. An absent list changes
nothing. The bm25/hindsight CLI paths apply the same filter in
main(); bm25_rank itself stays the byte-for-byte original (the
Lens parity check compares it raw).

Freshness at the moment of use (WikiCitadel v1):
every displayed hit and every evidence-pack entry
carries the page's freshness annotation — verified_until /
reverify-due / supersession / source standing — computed by
the freshness section below from the registers and frontmatter
the wiki already keeps. A page with no signal renders
nothing: silence means no adverse signal on record, never
"verified fresh". tools/lens/lenslib.py mirrors the
computation, and the parity tests pin the agreement.

--engine hindsight (adapted from vectorize-io/hindsight,
MIT — see wiki/sources/hindsight.md) fuses retrieval STRATEGIES the
way Hindsight's recall does: BM25 (keyword), the PPR graph walk
(entity/link structure), and — only when the query carries temporal
intent (latest / current / a month / a year / when …) — a temporal
strategy that ranks the candidate set by page date. The strategy
rankings are merged by reciprocal rank fusion (RRF, k = 60), then a
deterministic term-coverage rerank lifts documents whose title and
body actually cover the query's terms. Hindsight's fourth strategy
(dense-vector semantic) has no local counterpart — there is no
embedding endpoint on this machine — so BM25 stands in that slot;
the strategy list in hindsight_rank() is where a vector strategy
plugs in if one ever exists.

Attribution: the hybrid shape (BM25 + wikilink graph expansion
assembled into evidence packs with explicit omissions) is adapted
from atomicstrata/llm-wiki-compiler (MIT) and swarmvault (MIT);
personalized-PageRank retrieval follows the approach benchmarked
by gd4ai/obsidian-llm-wiki (Apache-2.0). Embeddings are deliberately
absent (no embedding endpoint exists on this machine); the ranker
interface keeps them pluggable behind hybrid_rank().
"""
