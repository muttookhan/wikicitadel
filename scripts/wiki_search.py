# Exact-title / stem-match boost + rank expressions (Marathon R3 TB7)
#
# title_match_kind(query_terms, title, stem): "exact" when the
# query token sequence equals the title token sequence or the
# file-stem token sequence; "stem" when the STEMMED token sets are
# equal (but not exact); else None. The boosts are sized to be
# decisive: the largest attainable pre-boost hybrid score is under
# 2.0 (normalised BM25 + alpha*PPR + temporal, times the rerank
# multiplier), so +10 (exact) / +5 (stem) cannot be outscored by
# corpus growth — an attested page titled by the query term stays
# at rank 1 while it is a candidate at all.
# tools/lens/lenslib.py and the Lens client (app.js) mirror these
# constants and rules exactly, and the regression tests pin the
# agreement.
# ---------------------------------------------------------------------------

TITLE_EXACT_BOOST = 10.0
TITLE_STEM_BOOST = 5.0


def stem_token(tok: str) -> str:
    """A small deterministic stemmer (suffix rules only): running
    -> run, reflections -> reflection, studies -> study. Used ONLY
    for the title/stem match; the corpus tokenizer is untouched."""
    t = tok.lower()
    if len(t) > 4 and t.endswith("ies"):
        t = t[:-3] + "y"
    elif len(t) > 5 and t.endswith("ing"):
        t = t[:-3]
    elif len(t) > 4 and t.endswith("ed"):
        t = t[:-2]
    elif len(t) > 3 and t.endswith("es") and not t.endswith("ss"):
        t = t[:-2]
    elif len(t) > 3 and t.endswith("s") and not t.endswith("ss"):
        t = t[:-1]
    if len(t) > 3 and t[-1] == t[-2] and t[-1] not in "aeiou":
        t = t[:-1]
    return t


def title_match_kind(query_terms, title, stem):
    """("exact" | "stem" | None) for a query against a page's
    title text and file stem (see the section header)."""
    q = [str(t).lower() for t in query_terms]
    if not q:
        return None
    title_toks = tokenize(title or "")
    stem_toks = tokenize((stem or "").replace("-", " "))
    if q == title_toks or q == stem_toks:
        return "exact"
    q_stems = {stem_token(t) for t in q}
    for toks in (title_toks, stem_toks):
        if toks and q_stems == {stem_token(t) for t in toks}:
            return "stem"
    return None


def title_boost_value(query_terms, title, stem):
    """(boost, kind) — the additive boost for this match kind."""
    kind = title_match_kind(query_terms, title, stem)
    if kind == "exact":
        return TITLE_EXACT_BOOST, kind
    if kind == "stem":
        return TITLE_STEM_BOOST, kind
    return 0.0, None


# ---------------------------------------------------------------------------
# Rank expressions (Vespa-style single-pass rank expressions,
# re-implemented from the idea — Vespa is Apache-2.0; this is an
# independent implementation of the stated-expression concept).
#
# A rank expression is a small declarative arithmetic expression
# over named per-candidate FEATURES, evaluated in ONE pass over
# the candidate list: no expression may call another ranker or
# re-scan the corpus. Grammar:
#   expr   := term (('+' | '-') term)*
#   term   := factor (('*' | '/') factor)*
#   factor := NUMBER | FEATURE | FUNC '(' expr (',' expr)* ')'
#             | '(' expr ')' | '-' factor
# Functions: min, max, clamp(x, lo, hi), log1p, abs. Division by
# zero yields 0.0 (a feature ratio with no denominator carries no
# signal, it is not an error). Unknown features/functions and
# malformed expressions raise ValueError at parse time.
# ---------------------------------------------------------------------------

RANK_FEATURES = {
    "bm25", "bm25_norm", "ppr", "ppr_norm", "blend_norm",
    "temporal", "recency", "rerank", "coverage", "title_frac",
    "title_boost", "exact_title", "stem_title", "importance",
}

RANK_EXPRESSIONS = {
    # The current hybrid ranking, stated as one named expression:
    # the stage-2 blend renormalised by the candidate set's max
    # blend (blend_norm — the scale the abstention tau was
    # calibrated on) + the temporal component, scaled by the
    # coverage rerank multiplier, plus the decisive title boost.
    # hybrid_rank() evaluates THIS string, so the shipped ranking
    # and the stated expression cannot drift.
    "hybrid-current":
        "(blend_norm + 0.3 * temporal) * rerank"
        " + title_boost",
    "bm25-only": "bm25_norm + title_boost",
    "graph-lean": "bm25_norm + 1.2 * ppr_norm + title_boost",
    "fresh-lean": "(bm25_norm + 0.6 * ppr_norm) * rerank"
                  " + 0.5 * recency + title_boost",
    "importance-lean": "bm25_norm + 0.6 * ppr_norm"
                       " + 0.4 * importance + title_boost",
}

_RANK_TOKEN_RE = re.compile(
    r"\s*(?:(?P<num>\d+(?:\.\d+)?)|(?P<name>[a-z_][a-z0-9_]*)"
    r"|(?P<op>[+\-*/(),]))")
_RANK_FUNCS = {"min": (2, min), "max": (2, max),
               "log1p": (1, math.log1p), "abs": (1, abs),
               "clamp": (3, lambda x, lo, hi: max(lo, min(hi, x)))}


def parse_rank_expression(text):
    """Parse a rank expression into an AST of tuples:
    ("num", v) | ("feat", name) | ("bin", op, l, r) |
    ("neg", x) | ("call", name, [args]). Raises ValueError."""
    tokens = []
    pos = 0
    while pos < len(text):
        m = _RANK_TOKEN_RE.match(text, pos)
        if not m or m.end() == pos:
            raise ValueError(f"rank expression: bad token at {pos}")
        pos = m.end()
        if m.group("num") is not None:
            tokens.append(("num", float(m.group("num"))))
        elif m.group("name") is not None:
            tokens.append(("name", m.group("name")))
        else:
            tokens.append(("op", m.group("op")))
    tokens.append(("op", "$"))
    state = {"i": 0}

    def peek():
        return tokens[state["i"]]

    def take():
        tok = tokens[state["i"]]
        state["i"] += 1
        return tok

    def parse_expr():
        node = parse_term()
        while peek() in (("op", "+"), ("op", "-")):
            op = take()[1]
            node = ("bin", op, node, parse_term())
        return node

    def parse_term():
        node = parse_factor()
        while peek() in (("op", "*"), ("op", "/")):
            op = take()[1]
            node = ("bin", op, node, parse_factor())
        return node

    def parse_factor():
        kind, val = take()
        if kind == "num":
            return ("num", val)
        if kind == "op" and val == "-":
            return ("neg", parse_factor())
        if kind == "op" and val == "(":
            node = parse_expr()
            if take() != ("op", ")"):
                raise ValueError("rank expression: missing )")
            return node
        if kind == "name":
            if peek() == ("op", "("):
                if val not in _RANK_FUNCS:
                    raise ValueError(
                        f"rank expression: unknown function {val}")
                take()
                args = [parse_expr()]
                while peek() == ("op", ","):
                    take()
                    args.append(parse_expr())
                if take() != ("op", ")"):
                    raise ValueError("rank expression: missing )")
                if len(args) != _RANK_FUNCS[val][0]:
                    raise ValueError(
                        f"rank expression: {val} takes "
                        f"{_RANK_FUNCS[val][0]} argument(s)")
                return ("call", val, args)
            if val not in RANK_FEATURES:
                raise ValueError(
                    f"rank expression: unknown feature {val}")
            return ("feat", val)
        raise ValueError("rank expression: unexpected token")

    ast = parse_expr()
    if peek() != ("op", "$"):
        raise ValueError("rank expression: trailing input")
    return ast


def eval_rank_expression(ast, features):
    """Evaluate a parsed rank expression against a feature dict.
    Missing features read as 0.0. One call per candidate — the
    single pass of the Vespa pattern."""
    kind = ast[0]
    if kind == "num":
        return ast[1]
    if kind == "feat":
        return float(features.get(ast[1], 0.0))
    if kind == "neg":
        return -eval_rank_expression(ast[1], features)
    if kind == "call":
        fn = _RANK_FUNCS[ast[1]][1]
        return float(fn(*[eval_rank_expression(a, features)
                          for a in ast[2]]))
    _k, op, left, right = ast
    lv = eval_rank_expression(left, features)
    rv = eval_rank_expression(right, features)
    if op == "+":
        return lv + rv
    if op == "-":
        return lv - rv
    if op == "*":
        return lv * rv
    return lv / rv if rv else 0.0


_RANK_AST_CACHE = {}


def rank_expression_ast(name_or_text):
    """The parsed AST for a named expression (cached) or a raw
    expression string."""
    if name_or_text in RANK_EXPRESSIONS:
        text = RANK_EXPRESSIONS[name_or_text]
    else:
        text = name_or_text
    if text not in _RANK_AST_CACHE:
        _RANK_AST_CACHE[text] = parse_rank_expression(text)
    return _RANK_AST_CACHE[text]


def doc_date(text: str):
    """The page's date for the temporal strategy: frontmatter
    `updated`, else frontmatter `created`, else the earliest ISO
    date in the text, else None."""
    head = text[:3000]
    fm = {}
    for key, val in FM_DATE_RE.findall(head):
        fm.setdefault(key, val)
    if "updated" in fm:
        return fm["updated"]
    if "created" in fm:
        return fm["created"]
    m = DATE_RE.search(head)
    return m.group(1) if m else None


def doc_title(text: str) -> str:
    m = TITLE_RE.search(text[:3000])
    if m:
        return m.group(1).strip()
    m = H1_RE.search(text)
    return m.group(1).strip() if m else ""


def temporal_intent(query_terms) -> bool:
    """Does the query ask about time? (latest/current/when, a month
    name, or a year token.) Hindsight's temporal strategy is
    query-driven — time-range filtering — so ours only joins the
    fusion when the query signals it."""
    qset = set(query_terms)
    if qset & TEMPORAL_TERMS or qset & MONTH_TERMS:
        return True
    return any(YEAR_RE.match(t) for t in qset)


def hindsight_rank(query_terms, docs, adj=None):
    """Hindsight-style recall: fuse strategy rankings by RRF, then
    rerank by term coverage. Strategies: (1) BM25 keyword ranking;
    (2) graph ranking by PPR value (structural pages receive no
    graph component, the hybrid rule); (3) temporal ranking of the
    candidate set by page date — only under temporal intent.
    Candidate set = the hybrid candidate set (BM25 hit, or graph
    hit clearing PPR_GRAPH_FLOOR), so the strategy fusion reorders
    evidence the existing engine already surfaces; it does not
    invent a new corpus. Returns the hybrid tuple shape
    (score, path, text, detail)."""
    base = bm25_rank(query_terms, docs)
    if not base:
        return []
    if adj is None:
        adj = build_link_graph(docs)
    index_of = {p: i for i, (p, _t) in enumerate(docs)}
    bm25_rank_of = {}
    bm25_by_idx = {}
    for rank, (score, p, _t) in enumerate(base, start=1):
        bm25_rank_of[index_of[p]] = rank
        bm25_by_idx[index_of[p]] = score
    seeds = {}
    for score, p, _t in base[:PPR_SEEDS]:
        seeds[index_of[p]] = score
    ppr = personalized_pagerank(adj, seeds)
    max_p = max(ppr.values()) if ppr else 0.0

    def graph_value(i, p):
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)
        if rel in STRUCTURAL_PATHS:
            return 0.0
        return ppr.get(i, 0.0)

    candidates = []
    for i, (p, text) in enumerate(docs):
        b = bm25_by_idx.get(i, 0.0)
        pr = graph_value(i, p)
        if b <= 0 and not (max_p > 0 and pr >= PPR_GRAPH_FLOOR * max_p):
            continue
        candidates.append(i)
    if not candidates:
        return []

    graph_order = sorted(candidates,
                         key=lambda i: (-graph_value(i, docs[i][0]),
                                        str(docs[i][0])))
    graph_rank_of = {i: r + 1 for r, i in enumerate(graph_order)
                     if graph_value(i, docs[i][0]) > 0}

    use_temporal = temporal_intent(query_terms)
    temporal_rank_of = {}
    if use_temporal:
        def date_key(i):
            d = doc_date(docs[i][1])
            return (d is not None, d or "", bm25_by_idx.get(i, 0.0))
        temporal_order = sorted(candidates, key=date_key, reverse=True)
        # stable, path-ordered ties: re-sort by path first
        temporal_order = sorted(
            sorted(candidates, key=lambda i: str(docs[i][0])),
            key=date_key, reverse=True)
        temporal_rank_of = {i: r + 1 for r, i in enumerate(temporal_order)}

    qset = set(query_terms)
    fused = []
    for i in candidates:
        p, text = docs[i]
        rrf = 0.0
        strategies = []
        if i in bm25_rank_of:
            rrf += 1.0 / (RRF_K + bm25_rank_of[i])
            strategies.append("bm25")
        if i in graph_rank_of:
            rrf += 1.0 / (RRF_K + graph_rank_of[i])
            strategies.append("graph")
        if i in temporal_rank_of:
            rrf += 1.0 / (RRF_K + temporal_rank_of[i])
            strategies.append("temporal")
        fused.append((rrf, i, strategies))
    fused.sort(key=lambda r: (-r[0], str(docs[r[1]][0])))

    out = []
    for pos, (rrf, i, strategies) in enumerate(fused):
        p, text = docs[i]
        score = rrf
        if pos < RERANK_POOL:
            toks = set(tokenize(text))
            coverage = len(qset & toks) / len(qset) if qset else 0.0
            title_toks = set(tokenize(doc_title(text)))
            title_frac = len(qset & title_toks) / len(qset) if qset else 0.0
            score = rrf * (1.0 + RERANK_COVERAGE_W * coverage
                           + RERANK_TITLE_W * title_frac)
        boost, match_kind = title_boost_value(
            query_terms, doc_title(text), p.stem)
        out.append((score + boost, p, text, {
            "bm25": round(bm25_by_idx.get(i, 0.0), 4),
            "ppr": round(graph_value(i, p), 6),
            "via": "+".join(strategies) if strategies else "bm25",
            "rrf": round(rrf, 6),
            "temporal": use_temporal,
            "title_boost": boost, "title_match": match_kind,
        }))
    out.sort(key=lambda r: (-r[0], str(r[1])))
    return out


def make_snippet(text: str, query_terms, width: int = 170) -> str:
    """One line around the best query-term match.

    The best line is the one holding the most distinct query terms
    (ties: most total occurrences, then earliest). Picking the first
    matching line instead would surface the title line almost every
    time, which rarely shows why the document matched.
    """
    qset = set(query_terms)
    best_line = None
    best_key = None
    for pos, raw_line in enumerate(text.splitlines()):
        line = raw_line.strip()
        if not line:
            continue
        toks = tokenize(line)
        distinct = len(qset & set(toks))
        if distinct == 0:
            continue
        key = (distinct, sum(1 for t in toks if t in qset), -pos)
        if best_key is None or key > best_key:
            best_key = key
            best_line = line
    if best_line is None:
        return "(match in token stream; no single line holds a query term)"
    line = best_line
    if len(line) <= width:
        return line
    # Centre the window on the first matching token position.
    mpos = first_term_offset(line.lower(), qset)
    if mpos < 0:
        return line[:width] + "…"
    start = max(0, mpos - width // 3)
    end = start + width
    out = line[start:end]
    if start > 0:
        out = "…" + out
    if end < len(line):
        out = out + "…"
    return out


def index_matches(query_terms):
    """Pages whose wiki/index.md catalog line mentions a query term.

    Returns [(line_text, [resolved page paths])] in index order.
    """
    index_path = WIKI / "index.md"
    if not index_path.exists():
        return []
    qset = set(query_terms)
    by_stem = {}
    for p in iter_md(WIKI):
        by_stem.setdefault(p.stem, p)
    results = []
    link_re = re.compile(r"\[\[([^\]|#]+)")
    for line in index_path.read_text(encoding="utf-8", errors="ignore").splitlines():
        if not (qset & set(tokenize(line))):
            continue
        targets = link_re.findall(line)
        if not targets:
            continue
        pages = []
        for t in targets:
            t = t.strip()
            cand = by_stem.get(t) or by_stem.get(Path(t).name)
            if cand:
                pages.append(cand)
        results.append((line.strip(), pages))
    return results


def pageindex_matches(query_terms, limit=5, pageindex_dir=None):
    """Traverse the PageIndex artefacts (WikiCitadel v1;
    pattern: VectifyAI/OpenKB, Apache-2.0): long documents are
    searched by their section tree — title + extractive summary —
    and a hit lands on the exact section with its page range.

    Deliberately a SEPARATE result list, never merged into the
    hybrid ranking: the golden benchmark measures wiki-page
    retrieval, and source-section hits must not move those numbers.
    """
    import importlib.util
    pi_path = ROOT / "scripts" / "wiki_pageindex.py"
    if not pi_path.is_file():
        return []
    try:
        spec = importlib.util.spec_from_file_location("wiki_pageindex", pi_path)
        pi = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(pi)
        indexes = pi.load_indexes(pageindex_dir or pi.OUT_DIR)
    except Exception:
        return []
    qset = set(query_terms)
    scored = []
    for art in indexes:
        for node, trail in pi.flatten(art["tree"]):
            title_tokens = tokenize(node["title"])
            summary_tokens = tokenize(node.get("summary") or "")
            score = 3.0 * len(qset & set(title_tokens)) \
                + 1.0 * len(qset & set(summary_tokens))
            if score > 0:
                scored.append({
                    "source": art["source"],
                    "node": node["id"],
                    "trail": trail,
                    "pages": node["pages"],
                    "score": round(score, 3),
                    "summary": node.get("summary") or "",
                })
    scored.sort(key=lambda h: (-h["score"], h["source"], h["trail"]))
    return scored[:limit]


def build_evidence_pack(query, query_terms, ranked, top, scope, corpus_size,
                        index_hits=None, omitted_count=5, engine_label=None,
                        freshness_signals=None):
    """An evidence pack: what was included, and — explicitly — what
    was left out and why (swarmvault's context-pack discipline).

    Included and omitted entries alike carry a "freshness"
    record  whenever their page has a freshness
    signal — the annotation travels with the evidence, at the
    moment of use. Signal-less pages carry no key."""
    if freshness_signals is None:
        freshness_signals = default_freshness_signals()
    included = []
    for score, p, text, detail in ranked[:top]:
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)
        entry = {
            "path": rel,
            "score": round(score, 4),
            "bm25": detail["bm25"], "ppr": detail["ppr"], "via": detail["via"],
            "snippet": make_snippet(text, query_terms),
        }
        if "rerank_relevance" in detail:
            entry["rerank_relevance"] = detail["rerank_relevance"]
            entry["below_cutoff"] = bool(detail.get("below_cutoff"))
        if "expansion_bm25" in detail:
            entry["expansion_bm25"] = detail["expansion_bm25"]
        if "onehop_vote" in detail:
            entry["onehop_vote"] = detail["onehop_vote"]
        if "iteration" in detail:
            entry["iteration"] = detail["iteration"]
        if "governance" in detail:
            entry["governance"] = detail["governance"]
        fresh = freshness_record(rel, text, signals=freshness_signals)
        if fresh["line"]:
            entry["freshness"] = fresh
        included.append(entry)
    cut = ranked[top - 1][0] if 0 < top <= len(ranked) else None
    omitted = []
    for score, p, _text, detail in ranked[top:top + omitted_count]:
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)
        entry = {
            "path": rel,
            "score": round(score, 4),
            "bm25": detail["bm25"], "ppr": detail["ppr"], "via": detail["via"],
            "reason": f"ranked #{top + len(omitted) + 1}, below the top-{top} cut"
                      + (f" (cut score {cut:.3f})" if cut is not None else ""),
        }
        if "expansion_bm25" in detail:
            entry["expansion_bm25"] = detail["expansion_bm25"]
        if "onehop_vote" in detail:
            entry["onehop_vote"] = detail["onehop_vote"]
        if "iteration" in detail:
            entry["iteration"] = detail["iteration"]
        if "governance" in detail:
            entry["governance"] = detail["governance"]
        fresh = freshness_record(rel, _text, signals=freshness_signals)
        if fresh["line"]:
            entry["freshness"] = fresh
        omitted.append(entry)
    return {
        "query": query,
        "terms": query_terms,
        "engine": engine_label or "hybrid (bm25 + personalized pagerank over wikilinks)",
        "scope": scope,
        "corpus_docs": corpus_size,
        "total_ranked": len(ranked),
        "included": included,
        "omitted": omitted,
        "omitted_note": "Only the highest-ranked omissions are listed; "
                        f"{max(0, len(ranked) - top - len(omitted))} further "
                        "ranked results were also left out by the same cut.",
        "index_matches": [
            {"line": line,
             "pages": [str(p.relative_to(ROOT)) for p in pages]}
            for line, pages in (index_hits or [])],
    }


