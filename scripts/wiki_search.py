def build_link_graph(docs):
    """Undirected adjacency over the doc list: {idx: sorted [idx]}.

    Wikilinks are read from each doc's text with code spans/fences
    stripped (a `[[wikilink]]` quoted in backticks is syntax, not a
    link — the wiki_validate.py convention). Targets resolve by
    repo-relative path without suffix, then by file stem, then by
    basename stem — the same precedence the validator and the Lens
    use, so all three rankers walk the same graph.
    """
    by_key = {}
    for i, (p, _t) in enumerate(docs):
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)
        by_key.setdefault(Path(rel).stem, i)
        by_key.setdefault(str(Path(rel).with_suffix("")), i)
    adj = {i: set() for i in range(len(docs))}
    for i, (_p, text) in enumerate(docs):
        body = CODESPAN_RE.sub("", FENCE_RE.sub("", text))
        for target in LINK_RE.findall(body):
            t = target.strip()
            if not t:
                continue
            j = by_key.get(t) or by_key.get(Path(t).name)
            if j is None or j == i:
                continue
            adj[i].add(j)
            adj[j].add(i)
    return {i: sorted(js) for i, js in adj.items()}


def personalized_pagerank(adj, seeds, damping=PPR_DAMPING,
                          tol=1e-7, max_iter=200):
    """Power-iteration PPR. `seeds`: {idx: weight} (need not be
    normalised). Dangling nodes redistribute over the seed
    distribution, keeping the walk a proper PPR. Returns
    {idx: probability} over all nodes in adj."""
    n = len(adj)
    if n == 0 or not seeds:
        return {}
    total = float(sum(seeds.values())) or 1.0
    teleport = {i: seeds.get(i, 0.0) / total for i in adj}
    rank = dict(teleport)
    for _ in range(max_iter):
        dangling = sum(rank[i] for i in adj if not adj[i])
        new = {}
        for i in adj:
            incoming = 0.0
            for j in adj[i]:
                if adj[j]:
                    incoming += rank[j] / len(adj[j])
            new[i] = (1.0 - damping) * teleport[i] \
                + damping * (incoming + dangling * teleport[i])
        delta = sum(abs(new[i] - rank[i]) for i in adj)
        rank = new
        if delta < tol:
            break
    return rank


def hybrid_rank(query_terms, docs, adj=None, severance=None):
    """Hybrid recall: BM25 + PPR graph, then the two Hindsight
    stages . Returns [(score, path, text, detail)]
    sorted by (-score, path); detail = {"bm25": float, "ppr":
    float, "via": "bm25" | "graph" | "both", "temporal": float,
    "rerank": float}. Docs found only by the walk (bm25 == 0) are
    included when their PPR clears PPR_GRAPH_FLOOR of the maximum
    PPR — the walk must surface neighbours, not the whole
    connected component.

    Stage 3 (temporal): when the query carries temporal intent,
    each candidate gains TEMPORAL_W * (1 - date-rank share) over
    the candidate set, newest page first (ties: higher BM25, then
    path). Stage 4 (rerank): results in the top RERANK_POOL of
    the stage-2 order are scaled by 1 + RERANK_COVERAGE_W * (share
    of distinct query terms in the first RERANK_LEAD_TOKENS
    tokens) + RERANK_TITLE_W * (share in the title). Both stages
    were tuned on the golden set; see the module docstring for
    the measured before/after.

    Stage 5 (severance): the ranked list is filtered
    against the severance list (see apply_severance). The
    `severance` argument: None loads the default list from
    evaluation/retrieval-severance.json, False disables the
    stage, a dict is used as the list."""
    base = bm25_rank(query_terms, docs)
    if not base:
        return []
    if adj is None:
        adj = build_link_graph(docs)
    index_of = {p: i for i, (p, _t) in enumerate(docs)}
    bm25_by_idx = {}
    for score, p, _t in base:
        bm25_by_idx[index_of[p]] = score
    seeds = {}
    for score, p, _t in base[:PPR_SEEDS]:
        seeds[index_of[p]] = score
    ppr = personalized_pagerank(adj, seeds)
    max_b = max(bm25_by_idx.values())
    max_p = max(ppr.values()) if ppr else 0.0
    out = []
    for i, (p, text) in enumerate(docs):
        b = bm25_by_idx.get(i, 0.0)
        pr = ppr.get(i, 0.0)
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)
        if rel in STRUCTURAL_PATHS:
            pr = 0.0
        if b <= 0 and not (max_p > 0 and pr >= PPR_GRAPH_FLOOR * max_p):
            continue
        score = (b / max_b if max_b else 0.0) \
            + HYBRID_ALPHA * (pr / max_p if max_p else 0.0)
        via = "both" if b > 0 and pr > 0 else ("bm25" if b > 0 else "graph")
        out.append((score, p, text,
                    {"bm25": round(b, 4), "ppr": round(pr, 6), "via": via}))
    out.sort(key=lambda r: (-r[0], str(r[1])))
    if not out:
        return out

    # --- Stage 3: temporal component (intent-gated) ---
    temp_by_idx = {}
    if temporal_intent(query_terms):
        cand = [index_of[p] for _s, p, _t, _d in out]

        def _date_key(i):
            d = doc_date(docs[i][1])
            return (d is not None, d or "", bm25_by_idx.get(i, 0.0))

        t_order = sorted(sorted(cand, key=lambda i: str(docs[i][0])),
                         key=_date_key, reverse=True)
        n_cand = len(cand)
        for r, i in enumerate(t_order):
            temp_by_idx[i] = 1.0 - r / n_cand

    # --- Stage 4: coverage rerank over the stage-2 order ---
    qset = set(query_terms)
    max_s = out[0][0]
    final = []
    for pos, (score, p, text, detail) in enumerate(out):
        ns = score / max_s if max_s else 0.0
        i = index_of[p]
        t = temp_by_idx.get(i, 0.0)
        ns += TEMPORAL_W * t
        mult = 1.0
        if pos < RERANK_POOL and qset:
            lead = set(tokenize(text)[:RERANK_LEAD_TOKENS])
            cov = len(qset & lead) / len(qset)
            title_toks = set(tokenize(doc_title(text)))
            t_frac = len(qset & title_toks) / len(qset)
            mult = 1.0 + RERANK_COVERAGE_W * cov + RERANK_TITLE_W * t_frac
            ns *= mult
        detail = dict(detail, temporal=round(t, 4), rerank=round(mult, 4))
        final.append((ns, p, text, detail))
    final.sort(key=lambda r: (-r[0], str(r[1])))

    # --- Stage 5: retrieval severance  ---
    # Exclusion by register lookup, after every ranking stage:
    # severed pages, and carriers of a severed claim the query
    # itself hunts, are removed — never merely down-ranked. The
    # pass is recorded in LAST_SEVERANCE for the CLI / pack.
    sev = _resolve_severance(severance)
    LAST_SEVERANCE["applied"] = bool(sev)
    LAST_SEVERANCE["excluded"] = []
    if sev:
        final, excluded = apply_severance(final, query_terms, sev)
        LAST_SEVERANCE["excluded"] = excluded
    return final


def doc_date(text: str):
    """The page's date for the temporal strategy: frontmatter
    `updated`, else frontmatter `created`, else the earliest ISO
    date in the text, else None."""
    head = text[:3000]
    fm = {}
    for key, val in FM_DATE_RE.findall(head):
        fm.setdefault(key, val)
    if "updated" in fm:
        return fm["updated"]
    if "created" in fm:
        return fm["created"]
    m = DATE_RE.search(head)
    return m.group(1) if m else None


def doc_title(text: str) -> str:
    m = TITLE_RE.search(text[:3000])
    if m:
        return m.group(1).strip()
    m = H1_RE.search(text)
    return m.group(1).strip() if m else ""


def temporal_intent(query_terms) -> bool:
    """Does the query ask about time? (latest/current/when, a month
    name, or a year token.) Hindsight's temporal strategy is
    query-driven — time-range filtering — so ours only joins the
    fusion when the query signals it."""
    qset = set(query_terms)
    if qset & TEMPORAL_TERMS or qset & MONTH_TERMS:
        return True
    return any(YEAR_RE.match(t) for t in qset)


def hindsight_rank(query_terms, docs, adj=None):
    """Hindsight-style recall: fuse strategy rankings by RRF, then
    rerank by term coverage. Strategies: (1) BM25 keyword ranking;
    (2) graph ranking by PPR value (structural pages receive no
    graph component, the hybrid rule); (3) temporal ranking of the
    candidate set by page date — only under temporal intent.
    Candidate set = the hybrid candidate set (BM25 hit, or graph
    hit clearing PPR_GRAPH_FLOOR), so the strategy fusion reorders
    evidence the existing engine already surfaces; it does not
    invent a new corpus. Returns the hybrid tuple shape
    (score, path, text, detail)."""
    base = bm25_rank(query_terms, docs)
    if not base:
        return []
    if adj is None:
        adj = build_link_graph(docs)
    index_of = {p: i for i, (p, _t) in enumerate(docs)}
    bm25_rank_of = {}
    bm25_by_idx = {}
    for rank, (score, p, _t) in enumerate(base, start=1):
        bm25_rank_of[index_of[p]] = rank
        bm25_by_idx[index_of[p]] = score
    seeds = {}
    for score, p, _t in base[:PPR_SEEDS]:
        seeds[index_of[p]] = score
    ppr = personalized_pagerank(adj, seeds)
    max_p = max(ppr.values()) if ppr else 0.0

    def graph_value(i, p):
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)
        if rel in STRUCTURAL_PATHS:
            return 0.0
        return ppr.get(i, 0.0)

    candidates = []
    for i, (p, text) in enumerate(docs):
        b = bm25_by_idx.get(i, 0.0)
        pr = graph_value(i, p)
        if b <= 0 and not (max_p > 0 and pr >= PPR_GRAPH_FLOOR * max_p):
            continue
        candidates.append(i)
    if not candidates:
        return []

    graph_order = sorted(candidates,
                         key=lambda i: (-graph_value(i, docs[i][0]),
                                        str(docs[i][0])))
    graph_rank_of = {i: r + 1 for r, i in enumerate(graph_order)
                     if graph_value(i, docs[i][0]) > 0}

    use_temporal = temporal_intent(query_terms)
    temporal_rank_of = {}
    if use_temporal:
        def date_key(i):
            d = doc_date(docs[i][1])
            return (d is not None, d or "", bm25_by_idx.get(i, 0.0))
        temporal_order = sorted(candidates, key=date_key, reverse=True)
        # stable, path-ordered ties: re-sort by path first
        temporal_order = sorted(
            sorted(candidates, key=lambda i: str(docs[i][0])),
            key=date_key, reverse=True)
        temporal_rank_of = {i: r + 1 for r, i in enumerate(temporal_order)}

    qset = set(query_terms)
    fused = []
    for i in candidates:
        p, text = docs[i]
        rrf = 0.0
        strategies = []
        if i in bm25_rank_of:
            rrf += 1.0 / (RRF_K + bm25_rank_of[i])
            strategies.append("bm25")
        if i in graph_rank_of:
            rrf += 1.0 / (RRF_K + graph_rank_of[i])
            strategies.append("graph")
        if i in temporal_rank_of:
            rrf += 1.0 / (RRF_K + temporal_rank_of[i])
            strategies.append("temporal")
        fused.append((rrf, i, strategies))
    fused.sort(key=lambda r: (-r[0], str(docs[r[1]][0])))

    out = []
    for pos, (rrf, i, strategies) in enumerate(fused):
        p, text = docs[i]
        score = rrf
        if pos < RERANK_POOL:
            toks = set(tokenize(text))
            coverage = len(qset & toks) / len(qset) if qset else 0.0
            title_toks = set(tokenize(doc_title(text)))
            title_frac = len(qset & title_toks) / len(qset) if qset else 0.0
            score = rrf * (1.0 + RERANK_COVERAGE_W * coverage
                           + RERANK_TITLE_W * title_frac)
        out.append((score, p, text, {
            "bm25": round(bm25_by_idx.get(i, 0.0), 4),
            "ppr": round(graph_value(i, p), 6),
            "via": "+".join(strategies) if strategies else "bm25",
            "rrf": round(rrf, 6),
            "temporal": use_temporal,
        }))
    out.sort(key=lambda r: (-r[0], str(r[1])))
    return out


def make_snippet(text: str, query_terms, width: int = 170) -> str:
    """One line around the best query-term match.

    The best line is the one holding the most distinct query terms
    (ties: most total occurrences, then earliest). Picking the first
    matching line instead would surface the title line almost every
    time, which rarely shows why the document matched.
    """
    qset = set(query_terms)
    best_line = None
    best_key = None
    for pos, raw_line in enumerate(text.splitlines()):
        line = raw_line.strip()
        if not line:
            continue
        toks = tokenize(line)
        distinct = len(qset & set(toks))
        if distinct == 0:
            continue
        key = (distinct, sum(1 for t in toks if t in qset), -pos)
        if best_key is None or key > best_key:
            best_key = key
            best_line = line
    if best_line is None:
        return "(match in token stream; no single line holds a query term)"
    line = best_line
    if len(line) <= width:
        return line
    # Centre the window on the first matching token position.
    m = None
    for match in TOKEN_RE.finditer(line.lower()):
        if match.group(0) in qset:
            m = match
            break
    if m is None:
        return line[:width] + "…"
    start = max(0, m.start() - width // 3)
    end = start + width
    out = line[start:end]
    if start > 0:
        out = "…" + out
    if end < len(line):
        out = out + "…"
    return out


def index_matches(query_terms):
    """Pages whose wiki/index.md catalog line mentions a query term.

    Returns [(line_text, [resolved page paths])] in index order.
    """
    index_path = WIKI / "index.md"
    if not index_path.exists():
        return []
    qset = set(query_terms)
    by_stem = {}
    for p in iter_md(WIKI):
        by_stem.setdefault(p.stem, p)
    results = []
    link_re = re.compile(r"\[\[([^\]|#]+)")
    for line in index_path.read_text(encoding="utf-8", errors="ignore").splitlines():
        if not (qset & set(tokenize(line))):
            continue
        targets = link_re.findall(line)
        if not targets:
            continue
        pages = []
        for t in targets:
            t = t.strip()
            cand = by_stem.get(t) or by_stem.get(Path(t).name)
            if cand:
                pages.append(cand)
        results.append((line.strip(), pages))
    return results


def pageindex_matches(query_terms, limit=5, pageindex_dir=None):
    """Traverse the PageIndex artefacts (WikiCitadel v1;
    pattern: VectifyAI/OpenKB, Apache-2.0): long documents are
    searched by their section tree — title + extractive summary —
    and a hit lands on the exact section with its page range.

    Deliberately a SEPARATE result list, never merged into the
    hybrid ranking: the golden benchmark measures wiki-page
    retrieval, and source-section hits must not move those numbers.
    """
    import importlib.util
    pi_path = ROOT / "scripts" / "wiki_pageindex.py"
    if not pi_path.is_file():
        return []
    try:
        spec = importlib.util.spec_from_file_location("wiki_pageindex", pi_path)
        pi = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(pi)
        indexes = pi.load_indexes(pageindex_dir or pi.OUT_DIR)
    except Exception:
        return []
    qset = set(query_terms)
    scored = []
    for art in indexes:
        for node, trail in pi.flatten(art["tree"]):
            title_tokens = tokenize(node["title"])
            summary_tokens = tokenize(node.get("summary") or "")
            score = 3.0 * len(qset & set(title_tokens)) \
                + 1.0 * len(qset & set(summary_tokens))
            if score > 0:
                scored.append({
                    "source": art["source"],
                    "node": node["id"],
                    "trail": trail,
                    "pages": node["pages"],
                    "score": round(score, 3),
                    "summary": node.get("summary") or "",
                })
    scored.sort(key=lambda h: (-h["score"], h["source"], h["trail"]))
    return scored[:limit]


def build_evidence_pack(query, query_terms, ranked, top, scope, corpus_size,
                        index_hits=None, omitted_count=5, engine_label=None,
                        freshness_signals=None):
    """An evidence pack: what was included, and — explicitly — what
    was left out and why (swarmvault's context-pack discipline).

    Included and omitted entries alike carry a "freshness"
    record  whenever their page has a freshness
    signal — the annotation travels with the evidence, at the
    moment of use. Signal-less pages carry no key."""
    if freshness_signals is None:
        freshness_signals = default_freshness_signals()
    included = []
    for score, p, text, detail in ranked[:top]:
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)
        entry = {
            "path": rel,
            "score": round(score, 4),
            "bm25": detail["bm25"], "ppr": detail["ppr"], "via": detail["via"],
            "snippet": make_snippet(text, query_terms),
        }
        fresh = freshness_record(rel, text, signals=freshness_signals)
        if fresh["line"]:
            entry["freshness"] = fresh
        included.append(entry)
    cut = ranked[top - 1][0] if 0 < top <= len(ranked) else None
    omitted = []
    for score, p, _text, detail in ranked[top:top + omitted_count]:
        rel = str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)
        entry = {
            "path": rel,
            "score": round(score, 4),
            "bm25": detail["bm25"], "ppr": detail["ppr"], "via": detail["via"],
            "reason": f"ranked #{top + len(omitted) + 1}, below the top-{top} cut"
                      + (f" (cut score {cut:.3f})" if cut is not None else ""),
        }
        fresh = freshness_record(rel, _text, signals=freshness_signals)
        if fresh["line"]:
            entry["freshness"] = fresh
        omitted.append(entry)
    return {
        "query": query,
        "terms": query_terms,
        "engine": engine_label or "hybrid (bm25 + personalized pagerank over wikilinks)",
        "scope": scope,
        "corpus_docs": corpus_size,
        "total_ranked": len(ranked),
        "included": included,
        "omitted": omitted,
        "omitted_note": "Only the highest-ranked omissions are listed; "
                        f"{max(0, len(ranked) - top - len(omitted))} further "
                        "ranked results were also left out by the same cut.",
        "index_matches": [
            {"line": line,
             "pages": [str(p.relative_to(ROOT)) for p in pages]}
            for line, pages in (index_hits or [])],
    }


