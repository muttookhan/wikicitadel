#!/usr/bin/env python3
"""Citeproc-style bibliography trial over the citation lockfile.

Marathon R9 lane BB (ideas board R7 research, Tier A): the
Zettlr narrow slice — the editor itself is NOT a candidate
(Zettlr, GPL-3.0, ideas only); what is built is (a) this
renderer trial. It turns the EXISTING citation lockfile
(evaluation/citation-lockfile.json, built by
scripts/wiki_cite_lock.py) into a formatted bibliography in
ONE named style, as a DERIVED artefact — the lockfile is
never modified, and the bibliography asserts nothing the
lockfile does not carry (no authors, dates or titles are
invented for sources the lockfile does not name them for;
entries state page, claim, source path, line range and the
locked quoted text).

Named style: "lockfile author-date-source" — entries grouped
by cited source (alphabetical), numbered within the whole
bibliography, in the form:

    [n] <claim> — citing page <page> (line N), citing
        <source>#L<a>-L<b>: "<locked quoted text>"

Commands:
  render [--lockfile PATH] [--out FILE]   the bibliography
  trial  [--out FILE]                     render + write the
        standing trial artefact
        (evaluation/citeproc-trial.md) with its header
Exit 0 ok; 2 usage error. Stdlib only, no network.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCKFILE = ROOT / "evaluation" / "citation-lockfile.json"
TRIAL = ROOT / "evaluation" / "citeproc-trial.md"
STYLE_NAME = "lockfile author-date-source (citeproc trial)"


def load_lockfile(path=None):
    p = Path(path) if path else LOCKFILE
    return json.loads(p.read_text(encoding="utf-8"))


def entries(lock):
    """Bibliography entries, grouped by source then page/id."""
    cites = list(lock.get("citations") or [])
    return sorted(cites, key=lambda c: (c.get("source", ""),
                                        c.get("page", ""),
                                        c.get("id", "")))


def render_bibliography(lock):
    cites = entries(lock)
    lines = [f"# Bibliography — style: {STYLE_NAME}", "",
             f"{len(cites)} entr(ies) from the citation lockfile "
             f"(generated {lock.get('generated', 'unknown')}, "
             f"lockfile version {lock.get('lockfile_version', '?')}).",
             ""]
    current_source = None
    for n, c in enumerate(cites, 1):
        if c.get("source") != current_source:
            current_source = c.get("source")
            lines += [f"## {current_source}", ""]
        rng = c.get("range") or []
        span = (f"#L{rng[0]}-L{rng[1]}" if len(rng) == 2
                else "#L?" if not rng else f"#L{rng[0]}")
        exact = ((c.get("selector") or {}).get("exact") or "").strip()
        lines.append(
            f"[{n}] {c.get('claim', '').strip()} — citing page "
            f"{c.get('page', '?')} (line {c.get('page_line', '?')}), "
            f"citing {current_source}{span}: \"{exact}\"")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def trial_text(lock):
    header = ("<!-- DERIVED ARTEFACT — generated by "
              "scripts/wiki_citeproc.py trial from "
              "evaluation/citation-lockfile.json; do not edit "
              "by hand. Style: " + STYLE_NAME + ". The lockfile "
              "is the record; this bibliography invents no "
              "authors, dates or titles it does not carry. -->\n\n")
    return header + render_bibliography(lock)


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Render a bibliography from the citation lockfile.")
    ap.add_argument("command", choices=("render", "trial"))
    ap.add_argument("--lockfile", default=None)
    ap.add_argument("--out", default=None)
    args = ap.parse_args(argv)
    try:
        lock = load_lockfile(args.lockfile)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"wiki_citeproc: cannot read lockfile: {exc}",
              file=sys.stderr)
        return 2
    text = (trial_text(lock) if args.command == "trial"
            else render_bibliography(lock))
    out = Path(args.out) if args.out else (
        TRIAL if args.command == "trial" else None)
    if out:
        out.write_text(text, encoding="utf-8")
        print(f"wiki_citeproc: wrote {out} "
              f"({len(entries(lock))} entries, style: {STYLE_NAME})")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
