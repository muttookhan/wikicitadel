#!/usr/bin/env python3
"""Narration PLAN for image/video briefings (gap 15 remainder).

Extends the audio-briefing machinery (scripts/wiki_audio_brief.py,
the built gap-15 scoped form) with the remainder boarded on
wiki/ideas.md: generative narration beyond the audio script —
a PLAN for an image/video briefing, as DATA only:

  * a shot list: one shot per page section, each with a visual
    description (what is on screen), the narration text for
    that shot, and an estimated duration at the audio brief's
    stated reading speed (150 wpm);
  * the full narration script, assembled from the shots;
  * an asset manifest: every asset the plan needs (one visual
    asset per shot), each with kind, description, the section
    it illustrates, and status "needed" — assets are PLANNED,
    never generated.

No media is generated, no TTS is run, and no external call is
made — the plan says so on its face (plan["generated_media"]
is false and plan["external_calls"] is empty, pinned by tests).
The plan is the deliverable a human or a separate, separately
approved production step would work from.

Usage:
  python3 scripts/wiki_narration_plan.py wiki/concepts/example.md
  python3 scripts/wiki_narration_plan.py --page P --out plan.json

Stdlib only.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import wiki_audio_brief  # noqa: E402  the built gap-15 machinery

ROOT = Path(__file__).resolve().parent.parent
WPM = wiki_audio_brief.WPM  # one stated reading speed, shared
SECONDS_PER_SHOT_FLOOR = 4  # a shot never plans shorter than this


def sections_of(text):
    """Split a page body into (heading, lines) sections. The
    preamble before the first heading is the 'Opening' section."""
    body = wiki_audio_brief.drop_frontmatter(text)
    sections = []
    heading, lines = "Opening", []
    seen_h1 = False
    for raw in body.splitlines():
        s = raw.strip()
        if s.startswith("# ") and not seen_h1 and not sections \
                and heading == "Opening":
            seen_h1 = True  # the page H1 is the title, not a shot
            continue
        if s.startswith("## ") or s.startswith("# "):
            if lines:
                sections.append((heading, lines))
            heading = s.lstrip("# ").strip()
            lines = []
        else:
            lines.append(raw)
    if lines:
        sections.append((heading, lines))
    out = []
    for heading, raw_lines in sections:
        spoken = wiki_audio_brief.strip_markdown("\n".join(raw_lines))
        spoken = [s for s in spoken
                  if s.lower() != heading.lower()]
        if spoken:
            out.append((heading, spoken))
    return out


def build_plan(title, sections, source_page):
    shots, assets = [], []
    total_seconds = 0
    for i, (heading, lines) in enumerate(sections, start=1):
        narration = " ".join(lines)
        words = len(narration.split())
        seconds = max(SECONDS_PER_SHOT_FLOOR,
                      round(words / WPM * 60))
        total_seconds += seconds
        shot_id = f"shot-{i:02d}"
        asset_id = f"asset-{i:02d}"
        visual = (f"Title card for the section '{heading}'"
                  if i == 1 else
                  f"Visual supporting the section '{heading}' "
                  f"of {title}")
        shots.append({
            "shot_id": shot_id,
            "section": heading,
            "visual": visual,
            "narration": narration,
            "est_seconds": seconds,
            "asset_ref": asset_id,
        })
        assets.append({
            "asset_id": asset_id,
            "kind": "image",
            "description": visual,
            "for_shot": shot_id,
            "section": heading,
            "status": "needed",
        })
    return {
        "format": "narration-plan/1",
        "title": title,
        "source_page": source_page,
        "reading_speed_wpm": WPM,
        "est_total_seconds": total_seconds,
        "generated_media": False,
        "external_calls": [],
        "note": ("Plan only — shot list, narration script and "
                 "asset manifest as data. No image, video or "
                 "audio is generated by this tool, and no "
                 "external call is made."),
        "shots": shots,
        "narration_script": "\n\n".join(
            f"[{s['shot_id']}] {s['narration']}" for s in shots),
        "assets": assets,
    }


def plan_for_page(path, root=ROOT):
    p = Path(path)
    if not p.is_absolute():
        p = root / p
    text = p.read_text(encoding="utf-8")
    title = wiki_audio_brief.title_of(text, p.stem.replace("-", " "))
    try:
        rel = str(p.resolve().relative_to(Path(root).resolve()))
    except ValueError:
        rel = str(p)
    return build_plan(title, sections_of(text), rel)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("page", help="wiki page path")
    ap.add_argument("--out", default=None,
                    help="write the plan JSON here instead of stdout")
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)
    plan = plan_for_page(args.page, root=args.root)
    text = json.dumps(plan, indent=2, sort_keys=True)
    if args.out:
        Path(args.out).write_text(text + "\n", encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
