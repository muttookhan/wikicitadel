#!/usr/bin/env python3
"""wiki_export_loss.py — per-run export loss inventory.

Marathon R11 lane BB (ideas board line 161, Tier A;
obsidian-export pattern — pattern only, stdlib). Every export
run records what it could not carry, beside the artefact, so
export loss is MEASURED per run rather than discovered later.
This tool inventories the loss surface of the compiled layer
(the same page set scripts/wiki_export.py exports): per page
and in total —

  unresolved_wikilinks  [[target]] whose stem is no page in the
                        corpus (a plain-text/HTML export renders
                        them as dead text or drops them)
  embeds                ![[...]] file embeds (no text export
                        carries the embedded file)
  callouts              > [!type] blocks (flattened by exporters
                        that do not know the callout syntax)
  claim_markers         ^[cite: ...] markers (carried verbatim
                        by some exports, dropped by others)
  editorial_markers     bare {{cite}} / {{clarify}} /
                        {{disputed}} flags
  html_lines            lines carrying raw HTML tags

It is a REPORT beside the export path, never a gate: exit 0
whenever the inventory was produced, however much loss it
records. Output is deterministic (sorted pages, sorted
targets, no timestamps) so per-run inventories diff cleanly.

Usage:
  inventory [--root DIR] [--out-json FILE] [--out-md FILE]
Exit 0 inventory produced; 2 usage error. Stdlib only.
"""
import argparse, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXCLUDED_DIRS = {"access", "talk"}
STRUCTURAL = {"index.md", "log.md"}
WIKILINK_RE = re.compile(r"(?<!!)\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]")
EMBED_RE = re.compile(r"!\[\[([^\]]+)\]\]")
CALLOUT_RE = re.compile(r"^\s*>\s*\[!([A-Za-z]+)\]", re.M)
CLAIM_RE = re.compile(r"\^\[cite:\s*[^\]]+\]")
EDITORIAL_RE = re.compile(r"(?<!`)\{\{(cite|clarify|disputed)\}\}")
HTML_RE = re.compile(r"<[a-zA-Z][a-zA-Z0-9-]*(\s[^>]*)?>")


def page_set(root):
    wiki = Path(root) / "wiki"
    out = []
    for p in sorted(wiki.rglob("*.md")):
        rel = p.relative_to(wiki)
        if rel.parts[0] in EXCLUDED_DIRS and len(rel.parts) > 1:
            continue
        if len(rel.parts) == 1 and rel.name in STRUCTURAL:
            continue
        out.append(p)
    return out


def inventory(root):
    pages = page_set(root)
    stems = {p.stem for p in pages}
    per_page, totals = [], {
        "pages": len(pages), "unresolved_wikilinks": 0,
        "embeds": 0, "callouts": 0, "claim_markers": 0,
        "editorial_markers": 0, "html_lines": 0}
    unresolved_targets = {}
    for p in pages:
        text = p.read_text(encoding="utf-8", errors="replace")
        unres = sorted({m.group(1).strip() for m in
                        WIKILINK_RE.finditer(text)
                        if Path(m.group(1).strip()).stem not in stems
                        and not m.group(1).strip().startswith("raw/")})
        row = {
            "page": str(p.relative_to(Path(root))),
            "unresolved_wikilinks": unres,
            "embeds": sorted({m.group(1) for m in
                              EMBED_RE.finditer(text)}),
            "callouts": len(CALLOUT_RE.findall(text)),
            "claim_markers": len(CLAIM_RE.findall(text)),
            "editorial_markers": len(EDITORIAL_RE.findall(text)),
            "html_lines": sum(1 for line in text.splitlines()
                              if HTML_RE.search(line)),
        }
        for t in unres:
            unresolved_targets.setdefault(t, []).append(row["page"])
        totals["unresolved_wikilinks"] += len(unres)
        totals["embeds"] += len(row["embeds"])
        totals["callouts"] += row["callouts"]
        totals["claim_markers"] += row["claim_markers"]
        totals["editorial_markers"] += row["editorial_markers"]
        totals["html_lines"] += row["html_lines"]
        if (unres or row["embeds"] or row["callouts"] or
                row["claim_markers"] or row["editorial_markers"] or
                row["html_lines"]):
            per_page.append(row)
    return {"tool": "export-loss-inventory", "totals": totals,
            "unresolved_targets": {k: sorted(v) for k, v in
                                   sorted(unresolved_targets.items())},
            "pages_with_loss": per_page,
            "note": "Report only, never a gate: an export run "
                    "files this inventory beside its artefact."}


def render_md(inv):
    t = inv["totals"]
    lines = ["# Export loss inventory (per run)", "",
             "Generated by `scripts/wiki_export_loss.py inventory` "
             "— a report beside the export artefact, never a gate.",
             "",
             f"- Pages inventoried: {t['pages']}",
             f"- Unresolved wikilinks: {t['unresolved_wikilinks']} "
             f"({len(inv['unresolved_targets'])} distinct targets)",
             f"- Embeds: {t['embeds']}",
             f"- Callouts: {t['callouts']}",
             f"- Claim markers: {t['claim_markers']}",
             f"- Editorial markers: {t['editorial_markers']}",
             f"- HTML lines: {t['html_lines']}", "",
             "## Pages with loss", ""]
    for row in inv["pages_with_loss"]:
        lines.append(
            f"- `{row['page']}` — unresolved "
            f"{len(row['unresolved_wikilinks'])}, embeds "
            f"{len(row['embeds'])}, callouts {row['callouts']}, "
            f"claim markers {row['claim_markers']}, editorial "
            f"{row['editorial_markers']}, html lines "
            f"{row['html_lines']}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("inventory")
    p.add_argument("--root", default=str(ROOT))
    p.add_argument("--out-json")
    p.add_argument("--out-md")
    a = ap.parse_args(argv)
    inv = inventory(a.root)
    if a.out_json:
        Path(a.out_json).write_text(json.dumps(inv, indent=2,
            sort_keys=True) + "\n", encoding="utf-8")
    if a.out_md:
        Path(a.out_md).write_text(render_md(inv), encoding="utf-8")
    if not a.out_json and not a.out_md:
        print(json.dumps(inv, indent=2, sort_keys=True))
    else:
        t = inv["totals"]
        print(f"inventory: {t['pages']} pages, "
              f"{t['unresolved_wikilinks']} unresolved wikilinks, "
              f"{t['embeds']} embeds, {t['callouts']} callouts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
