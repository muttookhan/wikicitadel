#!/usr/bin/env python3
"""Truth-aware retrieval governance (W1.5, 2026-10-22).

The comprehensive research report's sharpest measured gap was
truth-aware retrieval: the directional (supersession) slice of
the extended eval scored citation coverage@10 of 0.50 — when a
query goes looking for a superseded form, the retrieval layer
could cut the dead form's cues (severance, item 20) but could
not tell a page that ASSERTS the dead form from the page that
RECORDS its replacement, so the current form's own page was
excluded with the carriers, and no surface could say what had
been withheld or why. This module is the governance layer that
closes that: it derives, from the wiki's OWN records — never a
parallel bookkeeping system —

  * CHAINS: for every severance entry, the successor pages the
    registers name as carrying the current form (a decision's
    source page and the pages its superseded_by record names;
    a treatment event's treated_by detail; a superseded page's
    own superseded_by / replaced_by pointer). A successor page
    is exempt from that entry's text-match exclusion in search:
    its dead-form text is the audit chain, recounted as history,
    and the exemption is recorded, never silent.

  * PAGE STATE: every wiki page's governance state folded from
    its frontmatter lifecycle (status; superseded_by /
    replaced_by pointers), its claim lifecycle (the outcomes
    fold of scripts/wiki_claims.py: candidate = proposed,
    rule = accepted, retired = withheld), its validity windows
    (an intention claim's `expires:` closes the window; an
    elapsed evidence TTL or a passed verified_until is a
    re-check owed — annotated, never a withholding, per the
    schema's own words), and the treatment register's standing
    for its claims. Pages in a withheld state are withheld
    from default retrieval WITH their reasons named; governed
    pages travel with their state in the result detail.

  * ABSENCE CERTIFICATES: when retrieval concludes "we do not
    know", the conclusion can be issued as a checkable
    artefact bound to the governance state hash — a sha256
    over the derived chains + page states. Recomputing the
    state either matches the certificate (the absence still
    holds against that state) or reports it STALE (the corpus
    moved; the certificate names the state it was issued
    against, so the disagreement is itself checkable).

  * RETIRE-AND-REPLACE: the claim-level act, performed as one
    operation through the machinery that owns each piece — the
    old claim page gains status: superseded + a superseded_by
    pointer, the replacement gains the inverse supersedes
    pointer, the treatment register records the negative
    treatment citing the act, the log records it, and both
    derived artefacts (severance, governance) are regenerated
    — so the evolution chain is complete and retrieval sees
    it in the same act. Validation is all-or-nothing: an
    invalid act writes nothing. The outcomes log is NOT
    touched: outcomes are reality's record, and an
    administrative retirement is not a measurement.

UNGOVERNED pages — the legacy majority, carrying no lifecycle
signal at all — are a state of their own, named here and in
the artefact's census: absence of state means UNGOVERNED,
never superseded. An ungoverned page is kept by default
retrieval, carries no governance detail, and is counted in
the census as ungoverned. Nothing in this module ever treats
a missing signal as an adverse one.

The artefact, evaluation/retrieval-governance.json, is
DERIVED — generated by this module from the decisions
register, the treatment register, the outcomes log, the
severance artefact and the wiki tree; never hand-edit
(regenerate: wiki_governance.py build). Generation is
deterministic: same records => same bytes.

Consumers: scripts/wiki_search.py stage 6 (+ the severance
successor exemption), tools/lens/lenslib.py (the mirror), and
the evidence pack's governance block. An absent artefact
changes nothing: every consumer falls back to the
pre-governance behaviour.

Ideas (mechanisms only, re-implemented in our own code — no
code taken): governance state as a retrieval-visible field
and supersession chains as first-class retrieval relations
(knaisoma/data-olympus, rwnalds/engram, TyKolt/kremis, via the
2026-10-21 comprehensive research report's Tier-1 rows).

Usage:
  python3 scripts/wiki_governance.py build     # (re)write the artefact
  python3 scripts/wiki_governance.py check     # exit 1 when stale
  python3 scripts/wiki_governance.py show      # summarise the artefact
  python3 scripts/wiki_governance.py state-hash
  python3 scripts/wiki_governance.py certify --query "..."
  python3 scripts/wiki_governance.py verify-cert CERT.json
  python3 scripts/wiki_governance.py retire-replace \
      --page wiki/<old>.md --replacement wiki/<new>.md \
      --reason "..." [--date YYYY-MM-DD]

Stdlib only. Also importable in-process (the consumers load
the artefact with load_governance() and read its chains and
page records).
"""
import argparse
import hashlib
import importlib.util
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GOVERNANCE_PATH = ROOT / "evaluation" / "retrieval-governance.json"
SEVERANCE_REL = "evaluation/retrieval-severance.json"
DECISIONS_REL = "evaluation/decisions-register.jsonl"
TREATMENT_REL = "evaluation/treatment-register.jsonl"
OUTCOMES_REL = "evaluation/outcomes.jsonl"

# Lifecycle statuses that withhold a page from default
# retrieval. `draft` is NOT one: in this corpus draft is the
# ordinary working state of compiled pages (standing rules
# pages carry it), so draft is recorded as a working state,
# never as "proposed" and never withheld. Proposed vs
# accepted lives where the corpus actually keeps it: the
# claim lifecycle (candidate vs rule) and the decisions
# register (superseded forms vs the current form).
WITHHOLD_STATUSES = ("superseded", "deprecated", "tombstoned",
                     "archived")

# Treatment severity — the strongest signal governs (citator
# practice, as in scripts/wiki_treatment.py and the freshness
# fold in scripts/wiki_search.py).
_TREATMENT_SEVERITY = {"followed": -1, "questioned": 1,
                       "caution": 2, "negative": 3}

_FM_RE = re.compile(r"^---\n(.*?)\n---\n", re.S)
_FM_LINE_RE = re.compile(r"^([A-Za-z_]+):\s*(.*)$")
_WIKI_PATH_RE = re.compile(r"wiki/[A-Za-z0-9_./-]+\.md")
_EMPTY_VALUES = ("", "null", "none", "~", "[]")

# Structural pages carry no governance state (the catalog and
# the ledger, as everywhere else in the tooling).
_EXCLUDED_PAGES = ("wiki/index.md", "wiki/log.md")
_EXCLUDED_PREFIXES = ("wiki/access/",)


def _load(name, filename):
    spec = importlib.util.spec_from_file_location(
        name, Path(__file__).with_name(filename))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _read_jsonl(path):
    """[(lineno, record)] for a JSONL register; malformed lines
    are skipped (the registers' own tools are the validators)."""
    out = []
    path = Path(path)
    if not path.is_file():
        return out
    for lineno, line in enumerate(
            path.read_text(encoding="utf-8",
                           errors="ignore").splitlines(), start=1):
        line = line.strip()
        if not line:
            continue
        try:
            out.append((lineno, json.loads(line)))
        except ValueError:
            continue
    return out


def _sha256(path):
    path = Path(path)
    if not path.is_file():
        return None
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _fm_scalars(text):
    """The frontmatter scalars of a page, read with the same
    line rule the freshness section of scripts/wiki_search.py
    uses, so every consumer reads the same values. List values
    are kept raw (governance reads scalars only)."""
    if not text:
        return {}
    m = _FM_RE.match(text)
    if not m:
        return {}
    fields = {}
    for line in m.group(1).splitlines():
        km = _FM_LINE_RE.match(line)
        if not km or km.group(1) in fields:
            continue
        val = km.group(2).strip()
        if val.startswith("[") and val.endswith("]"):
            fields[km.group(1)] = val
        else:
            fields[km.group(1)] = val.strip("\"'")
    return fields


def _parse_date(value):
    """ISO date -> date; None when unparseable."""
    if value is None:
        return None
    v = str(value).strip()
    if not v:
        return None
    try:
        return date.fromisoformat(v[:10])
    except ValueError:
        return None


def pointer_target(raw):
    """A frontmatter pointer's target as a repo-relative path
    (brackets, a leading wiki/ and a trailing .md normalised
    and restored), or None when the field is absent or carries
    an empty value."""
    if raw is None \
            or str(raw).strip().lower() in _EMPTY_VALUES:
        return None
    v = str(raw).strip().strip("[]").strip()
    if not v:
        return None
    if not v.startswith("wiki/"):
        v = "wiki/" + v
    if not v.endswith(".md"):
        v = v + ".md"
    return v


def _wiki_paths_in(text):
    """The repo-relative wiki page paths a text names, sorted."""
    if not text:
        return []
    return sorted(set(_WIKI_PATH_RE.findall(str(text))))


# -- Chains: who carries the current form of a severed claim ------------------

def build_chains(root=ROOT, severance=None):
    """{severance entry id: {"successors": [pages], "via": str,
    "dangling": [named pages that do not exist]}} — derived
    from the registers each entry cites:

      decision-form  the decision record's source page (the
                     current form is stated there) + every
                     wiki page the form's superseded_by
                     record names;
      treatment      every wiki page the treating record's
                     treated_by detail names;
      page           the page's own superseded_by /
                     replaced_by pointer target.

    A successor that does not exist on disk is reported under
    "dangling" and never exempts anything: the chain is only
    as strong as the record, and a broken pointer is a finding,
    not a silent pass."""
    root = Path(root)
    if severance is None:
        sev_mod = _load("wiki_severance_for_governance",
                        "wiki_severance.py")
        severance = sev_mod.load_severance(root / SEVERANCE_REL)
    if not severance:
        return {}
    decisions = {}
    for _ln, record in _read_jsonl(root / DECISIONS_REL):
        if record.get("kind") == "decision":
            for form in record.get("superseded_forms") or []:
                decisions[form.get("form_id")] = (record, form)
    treatments = {}
    for _ln, record in _read_jsonl(root / TREATMENT_REL):
        if record.get("kind") == "treatment":
            treatments[record.get("id")] = record
    chains = {}
    for entry in severance.get("entries") or []:
        eid = entry.get("id")
        kind = entry.get("kind")
        found, via = [], ""
        if kind == "decision-form":
            record, form = decisions.get(
                (entry.get("source") or {}).get("record_id"),
                (None, None))
            if record is not None:
                page = (record.get("source") or {}).get("page")
                if page:
                    found.append(page)
                found += _wiki_paths_in(form.get("superseded_by"))
                via = ("decisions register: source page + the "
                       "superseded_by record")
        elif kind == "treatment":
            record = treatments.get(
                (entry.get("source") or {}).get("record_id"))
            if record is not None:
                found += _wiki_paths_in(
                    (record.get("treated_by") or {}).get("detail"))
                via = "treatment register: treated_by detail"
        elif kind == "page":
            path = root / (entry.get("page") or "")
            if path.is_file():
                fields = _fm_scalars(path.read_text(
                    encoding="utf-8", errors="ignore"))
                for key in ("superseded_by", "replaced_by"):
                    target = pointer_target(fields.get(key))
                    if target:
                        found.append(target)
                via = "the page's own supersession pointer"
        successors, dangling = [], []
        for page in sorted(set(found)):
            if (root / page).is_file():
                successors.append(page)
            else:
                dangling.append(page)
        if successors or dangling:
            chains[eid] = {"successors": successors, "via": via,
                           "dangling": dangling}
    return chains


# -- Page state -----------------------------------------------------------------

def _outcome_statuses(root):
    """{claim page: candidate|rule|retired} folded from the
    outcomes log by scripts/wiki_claims.py's own rule."""
    claims = _load("wiki_claims_for_governance", "wiki_claims.py")
    by_page = {}
    for _ln, record in _read_jsonl(root / OUTCOMES_REL):
        if record.get("page"):
            by_page.setdefault(record["page"], []).append(record)
    return {page: claims.status_for(records)
            for page, records in by_page.items()}


def _treatment_standings(root):
    """{page: strongest treatment grade} across the register's
    events for claims on that page (the strongest signal
    governs — citator practice)."""
    best = {}
    for _ln, record in _read_jsonl(root / TREATMENT_REL):
        if record.get("kind") != "treatment":
            continue
        page = (record.get("subject") or {}).get("page")
        grade = record.get("grade")
        if not page or grade not in _TREATMENT_SEVERITY:
            continue
        if page not in best or _TREATMENT_SEVERITY[grade] \
                > _TREATMENT_SEVERITY[best[page]]:
            best[page] = grade
    return best


def page_governance(rel, text, today=None, outcome_status=None,
                    treatment_grade=None):
    """One page's governance record, or None when the page is
    UNGOVERNED (no lifecycle signal of any kind — the record's
    absence IS the ungoverned state, and it is never read as
    an adverse one).

    Record: {"state": "withheld" | "governed",
             "reasons": [named reasons, withholding first],
             "successor": repo path | None,
             "proposition": "proposed" | "accepted" | None,
             "lifecycle": frontmatter status | None,
             "validity": {...} | None}
    """
    today = today or date.today()
    fields = _fm_scalars(text)
    reasons = []
    withheld = False
    status = str(fields.get("status") or "").strip().lower() \
        or None
    successor = pointer_target(fields.get("superseded_by"))
    if successor is None and status == "tombstoned":
        successor = pointer_target(fields.get("replaced_by"))
    if status in WITHHOLD_STATUSES:
        withheld = True
        reasons.append(f"page-status-{status}")
    if successor is not None:
        withheld = True
        reasons.append(f"superseded-by {successor}")
    proposition = None
    validity = None
    if fields.get("claim"):
        if outcome_status == "retired":
            withheld = True
            reasons.append("claim-retired (outcomes log)")
            proposition = "proposed"
        elif outcome_status == "rule":
            proposition = "accepted"
        else:
            # candidate — including a claim page with no
            # outcomes at all: proposed, not yet settled.
            proposition = "proposed"
            reasons.append(
                "claim-candidate (proposed, unsettled — "
                "fewer than 3 outcomes on record)")
        if str(fields.get("claim_type") or "").strip().lower() \
                == "intention":
            expires = _parse_date(fields.get("expires"))
            if expires is not None:
                validity = {"kind": "intention",
                            "expires": expires.isoformat()}
                if expires < today:
                    withheld = True
                    reasons.append(
                        "validity-window-closed (intention "
                        f"expired {expires.isoformat()})")
    vu = _parse_date(fields.get("verified_until"))
    if vu is not None and vu < today:
        reasons.append(
            f"attestation-expired {vu.isoformat()} "
            "(re-check owed)")
    as_of = _parse_date(fields.get("evidence_as_of"))
    ttl = fields.get("evidence_ttl_days")
    if as_of is not None and ttl is not None:
        try:
            ttl_days = int(str(ttl).strip())
        except ValueError:
            ttl_days = None
        if ttl_days is not None:
            from datetime import timedelta
            if as_of + timedelta(days=ttl_days) < today:
                reasons.append(
                    "evidence-stale (TTL elapsed; "
                    "re-check owed)")
    if treatment_grade in ("caution", "negative"):
        reasons.append(
            f"treatment standing {treatment_grade} for a "
            "claim on this page (treatment register)")
    if not reasons and proposition is None:
        # No adverse signal, no claim proposition, nothing to
        # annotate: the page is UNGOVERNED (a bare working
        # status such as draft is not governance).
        return None
    return {"state": "withheld" if withheld else "governed",
            "reasons": reasons,
            "successor": successor,
            "proposition": proposition,
            "lifecycle": status,
            "validity": validity}


# -- Artefact ---------------------------------------------------------------------

def build_artefact(root=ROOT, today=None):
    """The full governance artefact, derived deterministically
    from the registers and the wiki tree."""
    root = Path(root)
    today = today or date.today()
    sev_mod = _load("wiki_severance_for_governance",
                    "wiki_severance.py")
    severance = sev_mod.load_severance(root / SEVERANCE_REL)
    chains = build_chains(root, severance)
    outcomes = _outcome_statuses(root)
    standings = _treatment_standings(root)
    successor_of = {}
    for eid, chain in chains.items():
        for page in chain.get("successors") or []:
            successor_of.setdefault(page, []).append(eid)
    pages = {}
    census = {"pages_total": 0, "ungoverned": 0, "governed": 0,
              "withheld": 0}
    wiki = root / "wiki"
    if wiki.is_dir():
        for path in sorted(wiki.rglob("*.md")):
            rel = path.relative_to(root).as_posix()
            if rel in _EXCLUDED_PAGES or any(
                    rel.startswith(prefix)
                    for prefix in _EXCLUDED_PREFIXES):
                continue
            census["pages_total"] += 1
            text = path.read_text(encoding="utf-8",
                                  errors="ignore")
            record = page_governance(
                rel, text, today,
                outcome_status=outcomes.get(rel),
                treatment_grade=standings.get(rel))
            if record is None:
                record = {}
            if rel in successor_of:
                if not record:
                    # Successor-only record, in the canonical
                    # field order page_governance emits.
                    record = {"state": "governed", "reasons": [],
                              "successor": None,
                              "proposition": None,
                              "lifecycle": None, "validity": None}
                record["reasons"].append(
                    "named successor for "
                    + ", ".join(sorted(successor_of[rel]))
                    + " (carries the current form)")
                record["successor_of"] = sorted(successor_of[rel])
            if not record:
                census["ungoverned"] += 1
                continue
            pages[rel] = record
            census["withheld" if record["state"] == "withheld"
                   else "governed"] += 1
    artefact = {
        "kind": "retrieval-governance", "version": 1,
        "generated_from": {
            "generator": "scripts/wiki_governance.py",
            "inputs": {
                DECISIONS_REL: _sha256(root / DECISIONS_REL),
                TREATMENT_REL: _sha256(root / TREATMENT_REL),
                OUTCOMES_REL: _sha256(root / OUTCOMES_REL),
                SEVERANCE_REL: _sha256(root / SEVERANCE_REL),
            },
        },
        "chains": chains,
        "pages": pages,
        "census": census,
    }
    artefact["state_hash"] = state_hash(artefact)
    return artefact


def state_hash(artefact):
    """The corpus governance state hash: a sha256 over the
    derived chains + page states (the operative state an
    absence certificate binds to)."""
    body = {"chains": artefact.get("chains") or {},
            "pages": artefact.get("pages") or {}}
    canonical = json.dumps(body, sort_keys=True,
                           ensure_ascii=False)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def render_artefact(artefact):
    return json.dumps(artefact, indent=1, ensure_ascii=False) \
        + "\n"


def load_governance(path=None):
    """The governance artefact dict, or None when absent or
    unreadable (every consumer then falls back to the
    pre-governance behaviour — an absent artefact must never
    become an adverse signal in itself)."""
    path = Path(path) if path else GOVERNANCE_PATH
    try:
        artefact = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if artefact.get("kind") != "retrieval-governance" \
            or not isinstance(artefact.get("pages"), dict):
        return None
    return artefact


def successor_map(governance):
    """{severance entry id: {successor page paths}} from an
    artefact — the exemption table search stage 5 consults."""
    out = {}
    for eid, chain in (governance.get("chains") or {}).items():
        pages = chain.get("successors") or []
        if pages:
            out[eid] = set(pages)
    return out


# -- Absence certificates ----------------------------------------------------------

def absence_certificate(query, terms, governance, today=None):
    """A checkable artefact naming the corpus state an
    absence conclusion was computed against. Issued only for
    a genuine absence (the caller verifies retrieval returned
    nothing); the certificate binds the query, the state hash
    and the register hashes the state was derived from."""
    today = today or date.today()
    return {
        "kind": "absence-certificate", "version": 1,
        "query": query,
        "terms": list(terms),
        "issued": today.isoformat(),
        "state_hash": (governance or {}).get("state_hash"),
        "basis": (governance or {}).get("generated_from"),
        "note": ("Retrieval over the wiki returned no evidence "
                 "for this query against the corpus governance "
                 "state named by state_hash. verify-cert "
                 "recomputes the state: a matching hash means "
                 "the absence still stands against that state; "
                 "a STALE verdict means the corpus moved and "
                 "the absence must be re-established."),
    }


def verify_certificate(cert, root=ROOT):
    """{"status": "match" | "stale", ...} — recompute the
    governance state from the live registers and compare."""
    current = build_artefact(root)
    cert_hash = cert.get("state_hash")
    return {"status": "match" if cert_hash == current["state_hash"]
            else "stale",
            "certificate_state_hash": cert_hash,
            "current_state_hash": current["state_hash"]}


# -- Retire-and-replace --------------------------------------------------------------

def _next_treatment_id(root):
    top = 0
    for _ln, record in _read_jsonl(root / TREATMENT_REL):
        rid = str(record.get("id") or "")
        m = re.fullmatch(r"treat-(\d+)", rid)
        if m:
            top = max(top, int(m.group(1)))
    return f"treat-{top + 1:04d}"


def retire_replace(root, page, replacement, reason, when=None):
    """Retire one claim page and install its replacement as
    ONE operation. Returns (ok, report_lines, exit_code).

    All-or-nothing validation first: every precondition is
    checked before a single byte is written, so an invalid
    act changes nothing anywhere. The write pass then lands
    in dependency order — the two pages' pointers, the
    treatment event, the log entry, and finally the two
    derived artefacts regenerated from the new state — and a
    failure mid-pass is reported as PARTIAL with exactly what
    landed named, loudly, rather than papered over."""
    root = Path(root)
    when = when or date.today()
    date_s = when.isoformat()
    validate = _load("wiki_validate_for_governance",
                     "wiki_validate.py")
    claims = _load("wiki_claims_for_governance",
                   "wiki_claims.py")
    problems = []
    old_path = root / page
    new_path = root / replacement
    if page == replacement:
        problems.append("page and replacement are the same page")
    if not page.startswith("wiki/") or not old_path.is_file():
        problems.append(f"page not found under wiki/: {page}")
    if not replacement.startswith("wiki/") \
            or not new_path.is_file():
        problems.append(
            f"replacement not found under wiki/: {replacement}")
    if not (reason or "").strip():
        problems.append("a reason is required")
    old_text = new_text = None
    old_claim = None
    if not problems:
        old_text = old_path.read_text(encoding="utf-8")
        new_text = new_path.read_text(encoding="utf-8")
        old_fm, _body = validate.parse_frontmatter(old_text)
        if not (old_fm or {}).get("claim"):
            problems.append(
                f"{page} carries no claim: frontmatter — "
                "retire-and-replace is a claim-level operation")
        else:
            old_claim = old_fm["claim"]
        old_state = page_governance(page, old_text, when)
        if old_state and old_state["state"] == "withheld":
            problems.append(
                f"{page} is already in a withheld state "
                f"({'; '.join(old_state['reasons'])})")
        new_state = page_governance(replacement, new_text, when)
        if new_state and new_state["state"] == "withheld":
            problems.append(
                f"replacement {replacement} is itself in a "
                f"withheld state ({'; '.join(new_state['reasons'])})"
                " — a replacement must be live")
        new_fm, _b = validate.parse_frontmatter(new_text)
        if (new_fm or {}).get("supersedes"):
            problems.append(
                f"replacement already declares supersedes: "
                f"{new_fm['supersedes']} — refusing to clobber "
                "a declared relation")
    if problems:
        lines = ["retire-and-replace refused — nothing written:"]
        lines += [f"  - {p}" for p in problems]
        return False, lines, 1
    # Stage every new content in memory before writing.
    staged_old = claims._set_fm_fields(old_text, {
        "status": "superseded",
        "superseded_by": replacement,
        "updated": date_s})
    staged_new = claims._set_fm_fields(new_text, {
        "supersedes": page, "updated": date_s})
    event = {
        "kind": "treatment", "id": _next_treatment_id(root),
        "date": date_s, "recorded": date_s,
        "subject": {"page": page, "claim": old_claim},
        "grade": "negative",
        "treated_by": {
            "source": "scripts/wiki_governance.py retire-replace",
            "detail": (f"Retired and replaced by {replacement} "
                       f"in one operation: {reason}")},
        "reason": reason,
    }
    landed = []
    try:
        old_path.write_text(staged_old, encoding="utf-8")
        landed.append(f"{page}: status superseded, "
                      f"superseded_by {replacement}")
        new_path.write_text(staged_new, encoding="utf-8")
        landed.append(f"{replacement}: supersedes {page}")
        register = root / TREATMENT_REL
        with register.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(event, ensure_ascii=False) + "\n")
        landed.append(f"{TREATMENT_REL}: {event['id']} "
                      "(grade negative, citing this act)")
        log_path = root / "wiki" / "log.md"
        with log_path.open("a", encoding="utf-8") as fh:
            fh.write(f"\n## [{date_s}] lint | Retire-and-replace: "
                     f"{page} superseded by {replacement} — "
                     f"{reason}\n")
        landed.append("wiki/log.md: entry appended")
        sev_mod = _load("wiki_severance_for_governance",
                        "wiki_severance.py")
        (root / SEVERANCE_REL).write_text(
            sev_mod.render_artefact(sev_mod.build_artefact(root)),
            encoding="utf-8")
        landed.append(f"{SEVERANCE_REL}: regenerated")
        GOVERNANCE_PATH_FOR(root).write_text(
            render_artefact(build_artefact(root)),
            encoding="utf-8")
        landed.append(f"{GOVERNANCE_PATH.name} artefact "
                      "regenerated (evaluation/)")
    except OSError as exc:
        lines = ["retire-and-replace PARTIAL — the writes below "
                 "LANDED; the operation did not complete:"]
        lines += [f"  landed: {item}" for item in landed]
        lines.append(f"  failure: {exc}")
        lines.append("  recovery: fix the cause, then run "
                     "wiki_severance.py build and "
                     "wiki_governance.py build to re-derive "
                     "the artefacts from the landed state.")
        return False, lines, 3
    lines = [f"retired {page} and installed {replacement} as "
             "one operation:"]
    lines += [f"  {item}" for item in landed]
    lines.append("  evolution chain: the predecessor stays "
                 "visible to audit (its page, the treatment "
                 "event, the log entry); default retrieval "
                 "withholds it as superseded.")
    return True, lines, 0


def GOVERNANCE_PATH_FOR(root):
    return Path(root) / "evaluation" / "retrieval-governance.json"


# -- CLI -----------------------------------------------------------------------------

def _cmd_build(args):
    artefact = build_artefact()
    GOVERNANCE_PATH.write_text(render_artefact(artefact),
                               encoding="utf-8")
    census = artefact["census"]
    print(f"wrote {GOVERNANCE_PATH.relative_to(ROOT)}: "
          f"{len(artefact['pages'])} governed pages, "
          f"{len(artefact['chains'])} chains, "
          f"{census['ungoverned']} ungoverned, "
          f"state_hash {artefact['state_hash'][:12]}…")
    return 0


def _cmd_check(args):
    on_disk = load_governance()
    if on_disk is None:
        print("governance: no artefact on disk "
              "(run wiki_governance.py build)")
        return 1
    fresh = build_artefact()
    canonical = lambda a: json.dumps(a, sort_keys=True,
                                     ensure_ascii=False)
    if canonical(on_disk) == canonical(fresh):
        print("governance: artefact is current")
        return 0
    print("governance: STALE — the registers or the wiki moved "
          "since the artefact was generated; run "
          "wiki_governance.py build")
    return 1


def _cmd_show(args):
    artefact = load_governance()
    if artefact is None:
        print("governance: no artefact on disk")
        return 1
    census = artefact["census"]
    print(f"state_hash: {artefact['state_hash']}")
    print(f"pages: {census['pages_total']} scanned — "
          f"{census['governed']} governed, "
          f"{census['withheld']} withheld, "
          f"{census['ungoverned']} ungoverned")
    for eid, chain in sorted(artefact["chains"].items()):
        print(f"  chain {eid}: successors "
              f"{', '.join(chain['successors'])}")
    for rel, record in sorted(artefact["pages"].items()):
        if record["state"] == "withheld":
            print(f"  WITHHELD {rel}: "
                  f"{'; '.join(record['reasons'])}")
    return 0


def _cmd_state_hash(args):
    artefact = load_governance() or build_artefact()
    print(state_hash(artefact))
    return 0


def _cmd_certify(args):
    search = _load("wiki_search_for_governance",
                   "wiki_search.py")
    governance = load_governance() or build_artefact()
    terms = search.tokenize(args.query)
    docs = search.collect_docs("wiki")
    adj = search.build_link_graph(docs)
    ranked = search.hybrid_rank(terms, docs, adj)
    if ranked:
        print(f"not absent: retrieval returned {len(ranked)} "
              f"results (top: {ranked[0][1]}); an absence "
              "certificate is issued only for a genuine absence")
        return 1
    cert = absence_certificate(args.query, terms, governance)
    print(json.dumps(cert, indent=1, ensure_ascii=False))
    return 0


def _cmd_verify_cert(args):
    cert = json.loads(Path(args.cert).read_text(
        encoding="utf-8"))
    verdict = verify_certificate(cert)
    print(f"{verdict['status']}: certificate state "
          f"{verdict['certificate_state_hash']}, current state "
          f"{verdict['current_state_hash']}")
    return 0 if verdict["status"] == "match" else 1


def _cmd_retire_replace(args):
    when = _parse_date(args.date) if args.date else None
    ok, lines, code = retire_replace(
        ROOT, args.page, args.replacement, args.reason, when)
    print("\n".join(lines))
    return code


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Truth-aware retrieval governance: chains, "
                    "page state, absence certificates, "
                    "retire-and-replace.")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    sub.add_parser("check")
    sub.add_parser("show")
    sub.add_parser("state-hash")
    certify = sub.add_parser("certify")
    certify.add_argument("--query", required=True)
    verify = sub.add_parser("verify-cert")
    verify.add_argument("cert")
    retire = sub.add_parser("retire-replace")
    retire.add_argument("--page", required=True)
    retire.add_argument("--replacement", required=True)
    retire.add_argument("--reason", required=True)
    retire.add_argument("--date")
    args = parser.parse_args(argv)
    handler = {"build": _cmd_build, "check": _cmd_check,
               "show": _cmd_show, "state-hash": _cmd_state_hash,
               "certify": _cmd_certify,
               "verify-cert": _cmd_verify_cert,
               "retire-replace": _cmd_retire_replace}[args.cmd]
    return handler(args)


if __name__ == "__main__":
    sys.exit(main())
