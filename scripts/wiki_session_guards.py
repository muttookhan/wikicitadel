#!/usr/bin/env python3
"""Mechanical session guards (Wave-5 build, 2026-10-22).

Pattern sources are IDEAS only — Vellum Labs' written
disciplines (enforce raw immutability mechanically; a
session cannot end with the wiki dirty) and the
DHKIM0207/llm-wiki-kit hook shapes, via the wave-3/5
surveys. Clean re-implementation in this wiki's register
style; no code copied.

Three disciplines that used to rest on instructions alone,
made mechanical as deterministic local commands, each
registered as DATA in evaluation/hooks.jsonl and run by
scripts/wiki_hooks.py:

  precompact     (step "precompact", pre) — before a
      context compaction, PROPOSE filing the session's
      substance so nothing talked about is lost to
      compaction (the wiki's base purpose). The guard
      reads artefacts only — it cannot see the
      conversation — so it always prints the reminder,
      and it HALTS when artefacts show unfiled substance:
      uncommitted changes, unpushed commits, or capture
      drafts still sitting in staging/captures/ or
      staging/inbox/. It files NOTHING itself: filing is
      the agent's act, proposed here, never performed
      silently by the guard.
  session-clean  (step "session-end", pre) — refuse to
      end a session while the repo is dirty or carries
      unpushed commits. The report names every dirty path
      and every unpushed commit. With a session-start
      marker (.git/wiki-session-start.json, written by
      `session-clean --mark-start`) it separates this
      session's work from state that predates it; without
      one it says the separation cannot be made instead of
      guessing. A path already dirty at the mark is
      counted pre-existing even if the session also
      touched it — the marker cannot see inside a file.
  raw-audit      (step "session-end", pre) — the raw
      layer is append-only, checked against git: new
      files and pure appends (a diff that removes
      nothing) pass; a rewrite or deletion of a filed raw
      record fails, naming the file and the remedy.
  raw-guard      the write-time form of the same raw
      rule, for one intended write:
        raw-guard --path raw/... --op create|append|overwrite|delete

The raw allowlist — the ONLY overwrites of existing raw
files this wiki's own machinery performs, each an
exception named with its act:
  raw/sources/claude-memory/** — the nightly sweep's
      memory-mirror refresh re-copies the living memory
      files over their mirror images (and never deletes
      a mirror file; a vanished source leaves its mirror
      copy standing, flagged in the sweep report).
  raw/sources/provenance-manifest.json — regenerated by
      scripts/wiki_provenance.py from the tree itself
      whenever the mirror changes; a derived index, not
      a filed record.
Everything else under raw/: create and append pass,
overwrite and delete of an existing file are blocked.
Deletes are blocked everywhere under raw/, the mirror
included — retention acts go through their own machinery
(tombstone, erasure), never a bare delete.
Paths outside raw/ are outside this guard's jurisdiction
and pass with that stated: appends to CONVERSATION-LOG.md
and wiki/log.md are the standing examples, and the
filings pickup's verbatim writes are creates under
raw/filings/, which pass as new files.

Severity fits the hooks machinery as it stands: a guard
exits 0 (pass) or 1 (fired) and the registered hook halts
the step. The machinery has no warn level and none is
invented here; the report text carries the nuance. Every
firing prints WHAT fired, WHERE, and WHAT TO DO INSTEAD —
a silent block is a failed guard.

Pushed state is judged against the local remote-tracking
ref (what git last saw of azure), never the network, and
the report says so: hooks stay deterministic and local.

Usage:
  python3 scripts/wiki_session_guards.py precompact [--json]
  python3 scripts/wiki_session_guards.py session-clean [--mark-start] [--json]
  python3 scripts/wiki_session_guards.py raw-audit [--json]
  python3 scripts/wiki_session_guards.py raw-guard --path REL --op OP [--json]

Exit codes: 0 = pass / allowed, 1 = guard fired / blocked,
2 = usage error. Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

RAW_PREFIX = "raw/"
MIRROR_PREFIX = "raw/sources/claude-memory/"
PROVENANCE_MANIFEST = "raw/sources/provenance-manifest.json"
DRAFT_DIRS = ("staging/captures", "staging/inbox")
MARKER_NAME = "wiki-session-start.json"

REMINDER = [
    "PRECOMPACT GUARD — propose filing before this context is compacted.",
    "The wiki is the memory: what lives only in this conversation is",
    "lost when compaction lands. This guard files NOTHING itself — it",
    "reminds, and it halts when the artefacts show unfiled substance.",
    "It reads artefacts only and cannot see the conversation: if the",
    "session held decisions, corrections or facts that no artefact",
    "shows, the agent must still propose filing them now.",
]


def git(root: Path, *args: str):
    r = subprocess.run(["git", "-C", str(root), *args],
                       capture_output=True, text=True, timeout=120)
    return r.returncode, r.stdout


def parse_porcelain_z(out: str):
    """git status --porcelain -z -> [{xy, path, orig}] (orig
    is the rename/copy source path or None)."""
    entries = []
    toks = out.split("\0")
    i = 0
    while i < len(toks):
        tok = toks[i]
        i += 1
        if len(tok) < 4:
            continue
        xy, path = tok[:2], tok[3:]
        orig = None
        if "R" in xy or "C" in xy:
            if i < len(toks):
                orig = toks[i]
                i += 1
        entries.append({"xy": xy, "path": path, "orig": orig})
    return entries


def resolve_upstream(root: Path):
    """(ref, label) for the remote-tracking ref HEAD is
    judged against, or (None, reason). Local refs only."""
    rc, out = git(root, "rev-parse", "--abbrev-ref",
                  "--symbolic-full-name", "@{upstream}")
    if rc == 0 and out.strip():
        label = out.strip()
        return f"refs/remotes/{label}", label
    rc, out = git(root, "symbolic-ref", "--short", "HEAD")
    branch = out.strip() if rc == 0 else ""
    for remote in ("azure", "origin"):
        if branch:
            ref = f"refs/remotes/{remote}/{branch}"
            rc, _ = git(root, "rev-parse", "--verify", "--quiet", ref)
            if rc == 0:
                return ref, f"{remote}/{branch}"
    return None, "no upstream and no azure/origin tracking ref"


def session_state(root: Path):
    """The repo's filing-relevant state, from git alone."""
    rc, out = git(root, "symbolic-ref", "--short", "HEAD")
    branch = out.strip() if rc == 0 else "(detached HEAD)"
    _rc, out = git(root, "status", "--porcelain", "-z")
    dirty = parse_porcelain_z(out)
    ref, label = resolve_upstream(root)
    unpushed = None
    if ref:
        rc, out = git(root, "log", "--format=%H%x09%s", f"{ref}..HEAD")
        unpushed = []
        if rc == 0:
            for ln in out.splitlines():
                if "\t" in ln:
                    h, s = ln.split("\t", 1)
                    unpushed.append({"hash": h, "subject": s})
    return {"branch": branch, "upstream": label, "dirty": dirty,
            "unpushed": unpushed}


def marker_path(root: Path):
    rc, out = git(root, "rev-parse", "--git-dir")
    if rc != 0:
        return None
    gd = Path(out.strip())
    if not gd.is_absolute():
        gd = root / gd
    return gd / MARKER_NAME


def load_marker(root: Path):
    p = marker_path(root)
    if p is None or not p.is_file():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        return None


def draft_files(root: Path):
    found = []
    for d in DRAFT_DIRS:
        base = root / d
        if base.is_dir():
            for f in sorted(base.rglob("*")):
                if f.is_file():
                    found.append(f.relative_to(root).as_posix())
    return found


# ---------------------------------------------------------------
# Guard 1 — PreCompact propose-filing

def precompact_report(root: Path):
    st = session_state(root)
    drafts = draft_files(root)
    unpushed = st["unpushed"]
    fires = bool(st["dirty"]) or bool(unpushed) or bool(drafts)
    rep = {"guard": "precompact", "fires": fires,
           "branch": st["branch"], "upstream": st["upstream"],
           "dirty": [e["path"] for e in st["dirty"]],
           "unpushed": ([u["subject"] for u in unpushed]
                        if unpushed is not None else None),
           "drafts": drafts}
    return rep


def render_precompact(rep):
    lines = list(REMINDER)
    if not rep["fires"]:
        lines.append(
            "Artefact check: tree clean, nothing unpushed, no capture "
            "drafts waiting — no unfiled substance is visible. The "
            "reminder above stands anyway: the guard cannot see the "
            "conversation itself.")
        return lines
    lines.append("Unfiled substance detected — PROPOSE FILING before "
                 "compacting:")
    for p in rep["dirty"]:
        lines.append(f"  uncommitted change: {p}")
    if rep["unpushed"] is None:
        lines.append("  unpushed commits: cannot determine "
                     f"({rep['upstream']})")
    for s in rep["unpushed"] or []:
        lines.append(f"  unpushed commit: {s}")
    for p in rep["drafts"]:
        lines.append(f"  un-ingested capture draft: {p}")
    lines.append("What to do: file the session's substance (a "
                 "wiki/log.md entry and the compiled pages or "
                 "capture drafts it belongs on), commit and push, "
                 "then compact. The guard has filed nothing itself.")
    return lines


# ---------------------------------------------------------------
# Guard 2 — session-end cleanliness

def session_clean_report(root: Path):
    st = session_state(root)
    marker = load_marker(root)
    dirty_paths = [e["path"] for e in st["dirty"]]
    unpushed = st["unpushed"]
    rep = {"guard": "session-clean", "branch": st["branch"],
           "upstream": st["upstream"],
           "dirty": dirty_paths,
           "unpushed": ([{"hash": u["hash"][:12],
                          "subject": u["subject"]}
                         for u in unpushed]
                        if unpushed is not None else None),
           "marker": bool(marker)}
    if marker:
        m_dirty = set(marker.get("dirty_paths", []))
        m_unpushed = set(marker.get("unpushed_hashes", []))
        rep["session_dirty"] = [p for p in dirty_paths
                                 if p not in m_dirty]
        rep["preexisting_dirty"] = [p for p in dirty_paths
                                     if p in m_dirty]
        if unpushed is not None:
            rep["session_unpushed"] = [
                u["subject"] for u in unpushed
                if u["hash"] not in m_unpushed]
            rep["preexisting_unpushed"] = [
                u["subject"] for u in unpushed
                if u["hash"] in m_unpushed]
    rep["fires"] = bool(dirty_paths) or unpushed is None \
        or bool(unpushed)
    return rep


def render_session_clean(rep):
    state = "NOT CLEAN" if rep["fires"] else "clean"
    lines = [f"SESSION-END GUARD — the wiki repo is {state}.",
             f"Branch {rep['branch']}, pushed state judged against "
             f"{rep['upstream']} (the local remote-tracking ref — "
             "what git last saw of the remote; run git fetch to "
             "refresh it)."]
    if not rep["fires"]:
        lines.append("No uncommitted changes, no unpushed commits. "
                     "The session may end.")
        return lines
    if rep["marker"]:
        for label, key in (("this session's", "session_dirty"),
                           ("pre-existing", "preexisting_dirty")):
            for p in rep.get(key, []):
                lines.append(f"  dirty ({label}): {p}")
        for label, key in (("this session's", "session_unpushed"),
                           ("pre-existing", "preexisting_unpushed")):
            for s in rep.get(key, []):
                lines.append(f"  unpushed ({label}): {s}")
        lines.append("A path already dirty at the session-start "
                     "mark counts as pre-existing even if this "
                     "session also touched it; the mark cannot see "
                     "inside a file.")
    else:
        for p in rep["dirty"]:
            lines.append(f"  dirty: {p}")
        if rep["unpushed"] is None:
            lines.append("  unpushed: CANNOT DETERMINE — "
                         f"{rep['upstream']}. Unverified is not "
                         "clean, so the guard fires.")
        for u in rep["unpushed"] or []:
            lines.append(f"  unpushed: {u['hash']} {u['subject']}")
        lines.append("No session-start marker was recorded, so "
                     "this session's work cannot be separated from "
                     "pre-existing state; everything above is "
                     "reported as state at check time. Record the "
                     "mark at session start with: python3 "
                     "scripts/wiki_session_guards.py session-clean "
                     "--mark-start")
    lines.append("What to do: commit the work and push to azure, "
                 "or put on the record why it is left — a "
                 "successor session inherits a dirty tree blind.")
    return lines


def write_marker(root: Path):
    st = session_state(root)
    p = marker_path(root)
    if p is None:
        return None
    data = {"marked_at": datetime.now(timezone.utc).isoformat(),
            "branch": st["branch"],
            "dirty_paths": [e["path"] for e in st["dirty"]],
            "unpushed_hashes": [u["hash"] for u in
                                (st["unpushed"] or [])]}
    p.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n",
                 encoding="utf-8")
    return data


# ---------------------------------------------------------------
# Guard 3 — raw-layer immutability

def is_mirror(rel: str):
    return rel.startswith(MIRROR_PREFIX)


def classify_raw_write(root: Path, rel: str, op: str):
    """The write-time gate. (allowed, reason). rel is a
    repo-relative POSIX path; op is create|append|overwrite|delete."""
    rel = rel.replace("\\", "/").lstrip("./")
    if not rel.startswith(RAW_PREFIX):
        return True, (f"{rel} is outside raw/ — not this guard's "
                      "jurisdiction; the raw rule governs the raw "
                      "layer only.")
    exists = (root / rel).exists()
    if op == "create" and not exists:
        return True, (f"new raw file {rel} — the raw layer grows "
                      "by new files; filing is a create.")
    if op == "append":
        if not exists:
            return True, (f"{rel} does not exist yet — an append "
                          "to nothing is a create, which passes.")
        return True, (f"append to {rel} — an append preserves "
                      "every filed byte; the raw layer is "
                      "append-only and appends are its legal "
                      "write.")
    if op == "delete":
        if not exists:
            return True, f"{rel} does not exist — nothing to delete."
        return False, (f"BLOCKED: {rel} is a filed raw record and "
                       "raw records are never deleted. Retention "
                       "acts go through their own machinery "
                       "(tombstone / erasure, on the record); if a "
                       "mirror source vanished, the sweep leaves "
                       "the mirror copy standing and flags it "
                       "instead.")
    # overwrite, or create onto an existing file (judged as overwrite)
    if not exists:
        return True, (f"{rel} does not exist yet — an overwrite "
                      "of nothing is a create, which passes.")
    judged = "overwrite" if op == "overwrite" else \
        "create onto an existing file, judged as overwrite"
    if is_mirror(rel):
        return True, (f"{judged} allowed by the named exception: "
                      f"{rel} is in the memory mirror — the "
                      "nightly sweep re-copies the living memory "
                      "files over their mirror images under "
                      "raw/sources/claude-memory/ (and never "
                      "deletes a mirror file).")
    if rel == PROVENANCE_MANIFEST:
        return True, (f"{judged} allowed by the named exception: "
                      "raw/sources/provenance-manifest.json is "
                      "regenerated by scripts/wiki_provenance.py "
                      "from the tree itself whenever the mirror "
                      "changes — a derived index, not a filed "
                      "record.")
    return False, (f"BLOCKED: {rel} already exists and raw "
                   f"records are immutable once filed ({judged}). "
                   "File the new version as a NEW file — a dated "
                   "sibling under raw/ — and let the compiled "
                   "layer supersede; the only overwrites the raw "
                   "layer allows are the memory-mirror refresh "
                   "and the provenance-manifest regeneration, "
                   "each allowlisted by name.")


def numstat_deleted(root: Path, rel: str):
    """Lines a diff against HEAD removes from rel, or None
    when the diff cannot be read (binary, unborn HEAD)."""
    rc, out = git(root, "diff", "HEAD", "--numstat", "--", rel)
    if rc != 0 or not out.strip():
        return None
    parts = out.strip().splitlines()[0].split("\t")
    if len(parts) < 2 or parts[1] == "-":
        return None
    try:
        return int(parts[1])
    except ValueError:
        return None


def raw_audit_report(root: Path):
    _rc, out = git(root, "status", "--porcelain", "-z", "--", "raw/")
    entries = parse_porcelain_z(out)
    verdicts = []
    for e in entries:
        path, xy = e["path"], e["xy"]
        v = {"path": path, "status": xy.strip()}
        if xy == "??" or "A" in xy:
            v.update(kind="new", ok=True,
                     why="new raw file — the layer grows by creates")
        elif "D" in xy:
            v.update(kind="delete", ok=False,
                     why="a filed raw record is deleted in the "
                         "working tree; restore it (git checkout "
                         "-- <path>) — raw records are never "
                         "deleted")
        elif "R" in xy:
            v.update(kind="rename", ok=False,
                     why=f"renamed from {e.get('orig')} — a rename "
                         "removes the filed path and citations "
                         "resolve by path; file the new location "
                         "as a new file instead")
        elif "U" in xy:
            v.update(kind="conflict", ok=False,
                     why="unresolved merge conflict under raw/ — "
                         "resolve it without rewriting the filed "
                         "record")
        elif "M" in xy or "T" in xy:
            if is_mirror(path):
                v.update(kind="mirror-refresh", ok=True,
                         why="memory-mirror refresh — the sweep "
                             "re-copies living memory files over "
                             "their mirror images (named "
                             "exception)")
            elif path == PROVENANCE_MANIFEST:
                v.update(kind="provenance-regen", ok=True,
                         why="provenance manifest regenerated by "
                             "scripts/wiki_provenance.py from the "
                             "tree itself (named exception)")
            else:
                deleted = numstat_deleted(root, path)
                if deleted == 0:
                    v.update(kind="append", ok=True,
                             why="pure append — the diff removes "
                                 "nothing; every filed byte stands")
                elif deleted is None:
                    v.update(kind="rewrite", ok=False,
                             why="the change cannot be shown to "
                                 "be a pure append (binary or "
                                 "unreadable diff), so it is "
                                 "treated as a rewrite")
                else:
                    v.update(kind="rewrite", ok=False,
                             why=f"the diff removes or changes "
                                 f"{deleted} filed line(s) — raw "
                                 "records are immutable; file the "
                                 "new version as a new file and "
                                 "restore this one (git checkout "
                                 "-- <path>)")
        else:
            v.update(kind="other", ok=True, why=f"status {xy}")
        verdicts.append(v)
    bad = [v for v in verdicts if not v["ok"]]
    return {"guard": "raw-audit", "fires": bool(bad),
            "verdicts": verdicts, "violations": bad}


def render_raw_audit(rep):
    if not rep["verdicts"]:
        lines = ["RAW GUARD (audit) — raw/ is untouched in the "
                 "working tree: no creates, appends, rewrites or "
                 "deletions pending."]
        return lines
    lines = [f"RAW GUARD (audit) — {len(rep['verdicts'])} raw/ "
             f"change(s) in the working tree, "
             f"{len(rep['violations'])} violation(s):"]
    for v in rep["verdicts"]:
        mark = "ok  " if v["ok"] else "FIRE"
        lines.append(f"  [{mark}] {v['path']} ({v['kind']}): "
                     f"{v['why']}")
    if rep["violations"]:
        lines.append("What to do: restore each rewritten or "
                     "deleted record (git checkout -- <path>) and "
                     "file the new version as a NEW dated file "
                     "under raw/; the compiled layer, not the raw "
                     "layer, is where supersession lives.")
    return lines


# ---------------------------------------------------------------
# CLI

def emit(rep, lines, as_json):
    if as_json:
        print(json.dumps(rep, indent=2, sort_keys=True))
    else:
        print("\n".join(lines))


def cmd_precompact(root, as_json):
    rep = precompact_report(root)
    emit(rep, render_precompact(rep), as_json)
    return 1 if rep["fires"] else 0


def cmd_session_clean(root, mark_start, as_json):
    if mark_start:
        data = write_marker(root)
        if data is None:
            print("cannot locate the git dir; no marker written",
                  file=sys.stderr)
            return 2
        print(f"session-start marker written "
              f"({data['marked_at']}): {len(data['dirty_paths'])} "
              f"dirty path(s) and {len(data['unpushed_hashes'])} "
              "unpushed commit(s) predate this session.")
        return 0
    rep = session_clean_report(root)
    emit(rep, render_session_clean(rep), as_json)
    return 1 if rep["fires"] else 0


def cmd_raw_guard(root, rel, op, as_json):
    allowed, reason = classify_raw_write(root, rel, op)
    if as_json:
        print(json.dumps({"guard": "raw-guard", "path": rel,
                          "op": op, "allowed": allowed,
                          "reason": reason},
                         indent=2, sort_keys=True))
    else:
        verdict = "ALLOWED" if allowed else "BLOCKED"
        print(f"RAW GUARD: {verdict} — {reason}")
    return 0 if allowed else 1


def cmd_raw_audit(root, as_json):
    rep = raw_audit_report(root)
    emit(rep, render_raw_audit(rep), as_json)
    return 1 if rep["fires"] else 0


def main(argv):
    ap = argparse.ArgumentParser(
        description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=None)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("precompact", "raw-audit"):
        p = sub.add_parser(name)
        p.add_argument("--json", action="store_true")
    p = sub.add_parser("session-clean")
    p.add_argument("--mark-start", action="store_true")
    p.add_argument("--json", action="store_true")
    p = sub.add_parser("raw-guard")
    p.add_argument("--path", required=True)
    p.add_argument("--op", required=True,
                   choices=("create", "append", "overwrite",
                            "delete"))
    p.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)
    root = Path(args.root).resolve() if args.root else ROOT
    if args.cmd == "precompact":
        return cmd_precompact(root, args.json)
    if args.cmd == "session-clean":
        return cmd_session_clean(root, args.mark_start, args.json)
    if args.cmd == "raw-audit":
        return cmd_raw_audit(root, args.json)
    return cmd_raw_guard(root, args.path, args.op, args.json)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
