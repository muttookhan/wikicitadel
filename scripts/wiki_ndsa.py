#!/usr/bin/env python3
"""NDSA Levels of Digital Preservation — self-assessment support
(WikiCitadel v1).

Two halves, kept separate on purpose:

* MECHANICAL checks re-derive, from the tree itself, the
  practices that can be checked mechanically: how many copies
  exist (git remotes + the Drive copy *by record*), whether
  fixity information is stored, the file-format census, and
  whether access controls are documented. These are facts
  about the tree on the day the tool runs.

* JUDGEMENT rows live in ``evaluation/ndsa-judgements.json``
  (practice, verdict, evidence path, note). They are the
  assessing build's judgements, stated as such in the filing,
  open to the owner's correction; the tool only renders them.

The scorecard filing (``wiki/filings/ndsa-scorecard-*.md``)
is regenerated by running this tool and embedding its output.

Usage:
    python3 scripts/wiki_ndsa.py [--root DIR] [--json]

Exit code is always 0 on a completed run: a scorecard reports,
it does not gate.
"""

import argparse
import json
import subprocess
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JUDGEMENTS = Path("evaluation/ndsa-judgements.json")

# Where a Drive copy of this wiki is recorded. The check is
# "presence by record": the words must appear in a governing
# document, not merely in chat.
DRIVE_RECORD_FILES = (
    "AGENTS.md",
    "wiki/rules/succession.md",
    "wiki/syntheses/current-state.md",
)


def git_remotes(root):
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "remote"],
            capture_output=True, text=True, timeout=30,
        )
    except Exception:
        return []
    if out.returncode != 0:
        return []
    return [line.strip() for line in out.stdout.splitlines() if line.strip()]


def drive_copy_recorded(root):
    hits = []
    for rel in DRIVE_RECORD_FILES:
        p = root / rel
        if not p.is_file():
            continue
        text = p.read_text(encoding="utf-8", errors="replace").lower()
        if "google drive" in text and "zip" in text:
            hits.append(rel)
    return hits


def check_copies(root):
    remotes = git_remotes(root)
    drive = drive_copy_recorded(root)
    copies = 1 + len(remotes) + (1 if drive else 0)
    if copies >= 3:
        verdict = "MET"
    elif copies == 2:
        verdict = "PARTIAL"
    else:
        verdict = "NOT MET"
    detail = (
        f"{copies} copies accounted: the working tree, "
        f"{len(remotes)} git remote(s) [{', '.join(remotes) or 'none'}], "
        + ("a Google Drive zip copy recorded in "
           + ", ".join(drive) if drive else "no Drive copy on record")
    )
    return {
        "id": "copies",
        "practice": "Complete copies in separate locations "
                    "(NDSA Storage L1 two copies; L2 three copies)",
        "verdict": verdict, "detail": detail,
        "evidence": drive if drive else ["AGENTS.md"],
    }


def _manifest_entries(path):
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None
    if isinstance(data, dict):
        files = data.get("files", data)
        return len(files) if hasattr(files, "__len__") else None
    if isinstance(data, list):
        return len(data)
    return None


def _jsonl_lines(path):
    try:
        return sum(1 for line in path.read_text(encoding="utf-8").splitlines()
                   if line.strip())
    except Exception:
        return None


def check_fixity_stored(root):
    prov = root / "raw/sources/provenance-manifest.json"
    merkle = root / "evaluation/merkle-manifest.jsonl"
    source = root / "evaluation/source-manifest.jsonl"
    parts = []
    found = []
    n = _manifest_entries(prov) if prov.is_file() else None
    if n is not None:
        parts.append(f"provenance manifest covers {n} entries")
        found.append("raw/sources/provenance-manifest.json")
    m = _jsonl_lines(merkle) if merkle.is_file() else None
    if m:
        parts.append(f"Merkle manifest holds {m} source records")
        found.append("evaluation/merkle-manifest.jsonl")
    s = _jsonl_lines(source) if source.is_file() else None
    if s:
        parts.append(f"source manifest holds {s} per-source sha256 records")
        found.append("evaluation/source-manifest.jsonl")
    verdict = "MET" if n is not None else ("PARTIAL" if found else "NOT MET")
    return {
        "id": "fixity-stored",
        "practice": "Fixity information generated and stored "
                    "(NDSA Integrity L1/L2)",
        "verdict": verdict,
        "detail": "; ".join(parts) if parts else "no fixity manifest found",
        "evidence": found,
    }


def format_census(root):
    counts = Counter()
    total = 0
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(root)
        if rel.parts and rel.parts[0] == ".git":
            continue
        if "__pycache__" in rel.parts:
            continue
        ext = path.suffix.lower() or "(none)"
        counts[ext] += 1
        total += 1
    return counts, total


def check_format_census(root):
    counts, total = format_census(root)
    top = ", ".join(f"{ext} {n}" for ext, n in counts.most_common(8))
    return {
        "id": "format-census",
        "practice": "Inventory of file formats in use "
                    "(NDSA Content L2)",
        "verdict": "MET" if total else "NOT MET",
        "detail": f"{total} files in {len(counts)} extension classes; "
                  f"largest: {top}",
        "evidence": ["scripts/wiki_ndsa.py"],
        "census": dict(counts.most_common()),
    }


def check_access_documented(root):
    agents = root / "AGENTS.md"
    has_security = agents.is_file() and "## Security" in agents.read_text(
        encoding="utf-8", errors="replace")
    scopes_doc = root / "wiki/access/identity-scopes.md"
    gateway = root / "tools/gateway/README.md"
    evidence = [p for p, ok in (
        ("AGENTS.md", has_security),
        ("wiki/access/identity-scopes.md", scopes_doc.is_file()),
        ("tools/gateway/README.md", gateway.is_file()),
    ) if ok]
    verdict = "MET" if has_security and len(evidence) >= 2 else (
        "PARTIAL" if evidence else "NOT MET")
    return {
        "id": "access-documented",
        "practice": "Access controls documented (NDSA Control L2)",
        "verdict": verdict,
        "detail": ("AGENTS.md carries a Security section and the "
                   "gateway's identity scopes are written down"
                   if verdict == "MET" else
                   "access documentation incomplete: "
                   + (", ".join(evidence) or "none found")),
        "evidence": evidence,
    }


def mechanical_checks(root):
    return [
        check_copies(root),
        check_fixity_stored(root),
        check_format_census(root),
        check_access_documented(root),
    ]


def load_judgements(root):
    path = root / JUDGEMENTS
    if not path.is_file():
        return []
    return json.loads(path.read_text(encoding="utf-8"))


def render_markdown(root, checks, judgements):
    lines = []
    lines.append(f"Mechanical checks re-derived {date.today().isoformat()} "
                 f"by `scripts/wiki_ndsa.py`:")
    lines.append("")
    lines.append("| Check | Verdict | What the tree shows | Evidence |")
    lines.append("|---|---|---|---|")
    for c in checks:
        ev = "<br>".join(f"`{e}`" for e in c["evidence"]) or "—"
        lines.append(f"| {c['practice']} | **{c['verdict']}** | "
                     f"{c['detail']} | {ev} |")
    lines.append("")
    lines.append("Judgement rows (the assessing build's, from "
                 "`evaluation/ndsa-judgements.json`):")
    lines.append("")
    lines.append("| Area | Level | Practice | Verdict | Evidence | Note |")
    lines.append("|---|---|---|---|---|---|")
    for j in judgements:
        lines.append(
            f"| {j['area']} | {j['level']} | {j['practice']} | "
            f"**{j['verdict']}** | `{j['evidence']}` | {j['note']} |")
    lines.append("")
    tally = Counter(j["verdict"] for j in judgements)
    lines.append(f"Judgement tally: MET {tally.get('MET', 0)} · "
                 f"PARTIAL {tally.get('PARTIAL', 0)} · "
                 f"NOT MET {tally.get('NOT MET', 0)} "
                 f"of {len(judgements)} practices.")
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT,
                    help="repository root (default: this repo)")
    ap.add_argument("--json", action="store_true",
                    help="emit the checks + judgements as JSON")
    args = ap.parse_args(argv)
    root = args.root.resolve()
    checks = mechanical_checks(root)
    judgements = load_judgements(root)
    if args.json:
        print(json.dumps({"mechanical": checks, "judgements": judgements},
                         indent=2))
    else:
        print(render_markdown(root, checks, judgements))
    return 0


if __name__ == "__main__":
    sys.exit(main())
